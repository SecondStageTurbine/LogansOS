# Independent oracle for the #218 hardening (PM AAG, 2026-10-29): IPv6 NDP/RA
# frames laid out from RFC 8200 and RFC 4861 with RFC 4443 checksums, and DHCP
# OFFER/ACK messages laid out from RFC 2131 figure 1.
import struct
def csum(b):
    if len(b)%2: b+=b'\0'
    s=sum(struct.unpack('!%dH'%(len(b)//2),b))
    while s>>16: s=(s&0xffff)+(s>>16)
    return (~s)&0xffff
US=bytes.fromhex('525400123456'); PEER=bytes.fromhex('525400123457')
def v6(s): # compact hex, 32 digits
    return bytes.fromhex(s)
LL_PEER=v6('fe800000000000000000000000000002')
GLOBAL_PEER=v6('20010db8000000000000000000000002')
ALL_NODES=v6('ff020000000000000000000000000001')
OURS=v6('20010db8000000000200000000000000')   # the stable SLAAC address, iid 0x0200.. | 0
SOLICITED=v6('ff0200000000000000000001ff000000')
def icmp6(src,dst,body):
    ph=src+dst+struct.pack('!IxxxB',len(body),58)
    c=csum(ph+body)
    return body[:2]+struct.pack('!H',c)+body[4:]
def ip6(src,dst,payload,hop=255,nh=58):
    return struct.pack('!IHBB',6<<28,len(payload),nh,hop)+src+dst+payload
def eth(dst,src,p): return dst+src+b'\x86\xdd'+p
def ra(prefix):
    body=struct.pack('!BBHBBHII',134,0,0,64,0,1800,0,0)
    # Prefix Information: type 3, len 4, /64, L|A, valid 3600, preferred 1800
    body+=struct.pack('!BBBBIII',3,4,64,0xc0,3600,1800,0)+prefix
    return body
RA_BODY=ra(v6('20010db8000000000000000000000000'))
ns=struct.pack('!BBHI',135,0,0,0)+OURS+struct.pack('!BB',1,1)+PEER
na=struct.pack('!BBHI',136,0,0,0x60000000)+GLOBAL_PEER+struct.pack('!BB',2,1)+PEER
frames={
 'RA': eth(b'\x33\x33\x00\x00\x00\x01',PEER,ip6(LL_PEER,ALL_NODES,icmp6(LL_PEER,ALL_NODES,RA_BODY))),
 'RA_HOP_64': eth(b'\x33\x33\x00\x00\x00\x01',PEER,ip6(LL_PEER,ALL_NODES,icmp6(LL_PEER,ALL_NODES,RA_BODY),hop=64)),
 'RA_GLOBAL_SRC': eth(b'\x33\x33\x00\x00\x00\x01',PEER,ip6(GLOBAL_PEER,ALL_NODES,icmp6(GLOBAL_PEER,ALL_NODES,RA_BODY))),
 'NS': eth(b'\x33\x33\xff\x00\x00\x00',PEER,ip6(GLOBAL_PEER,SOLICITED,icmp6(GLOBAL_PEER,SOLICITED,ns))),
 'NA': eth(US,PEER,ip6(GLOBAL_PEER,OURS,icmp6(GLOBAL_PEER,OURS,na))),
}
def bootp(op,xid,yiaddr,chaddr,opts):
    return struct.pack('!BBBBIHH4s4s4s4s16s64s128s4s',op,1,6,0,xid,0,0,bytes(4),bytes(yiaddr),bytes(4),bytes(4),
        chaddr+bytes(10),bytes(64),bytes(128),bytes([99,130,83,99]))+opts+b'\xff'
OPTS=lambda t,server: bytes([53,1,t,54,4])+bytes(server)+bytes([51,4])+struct.pack('!I',600)
frames['DHCP_OFFER']=bootp(2,0x4e454f30,[10,0,0,10],US,OPTS(2,[10,0,0,2]))
frames['DHCP_ACK']=bootp(2,0x4e454f30,[10,0,0,10],US,OPTS(5,[10,0,0,2]))
frames['DHCP_NAK']=bootp(2,0x4e454f30,[0,0,0,0],US,bytes([53,1,6,54,4,10,0,0,2]))
