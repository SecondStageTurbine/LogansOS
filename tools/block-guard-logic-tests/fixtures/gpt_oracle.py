"""OT-87 R3: the hand-laid GPT byte oracle (docs/THINK-2026-10-27-ot87-installer.md §4.4, I-12).

Lays out, field by field from the THINK's table, the protective MBR, both GPT
headers and entries 1-2 of a 4 GiB disk at S=512 and at S=4096, with fixed
GUIDs. The CRC32s come from Python's zlib.crc32, independent of the Rust
writer (kernel/src/drivers/block/gpt_logic.rs), which this file never reads.

Writes ../src/gpt_oracle.rs: every non-zero byte of each structure, as
(offset, byte) pairs. Run from this directory: python3 gpt_oracle.py
"""
import struct
import uuid
import zlib

DISK_GUID = uuid.UUID("4c6f6761-6e4f-5321-8000-000000000001")
ESP_GUID = uuid.UUID("4c6f6761-6e4f-5321-8000-0000000000e5")
NEOFS_GUID = uuid.UUID("4c6f6761-6e4f-5321-8000-0000000000f5")
# UEFI 2.10 §5.3.3, and the LogansOS NeoFS type minted for R3.
ESP_TYPE = uuid.UUID("c12a7328-f81f-11d2-ba4b-00a0c93ec93b")
NEOFS_TYPE = uuid.UUID("eaa7a9d0-75c1-4385-9664-b2a74fc2622d")
DISK_BYTES = 4 * 1024**3


def entry(type_guid, unique, start, end, attrs, name):
    e = bytearray(128)
    e[0:16] = type_guid.bytes_le  # GPT stores GUIDs mixed-endian
    e[16:32] = unique.bytes_le
    e[32:40] = struct.pack("<Q", start)
    e[40:48] = struct.pack("<Q", end)
    e[48:56] = struct.pack("<Q", attrs)
    n = name.encode("utf-16-le")
    e[56:56 + len(n)] = n
    return bytes(e)


def header(s, my, alt, first, last, entries_lba, crc_e):
    h = bytearray(s)
    h[0:8] = b"EFI PART"
    h[8:12] = bytes([0x00, 0x00, 0x01, 0x00])  # revision 1.0
    h[12:16] = struct.pack("<I", 92)
    # @16 HeaderCRC32 stays zero while the CRC is taken
    h[24:32] = struct.pack("<Q", my)
    h[32:40] = struct.pack("<Q", alt)
    h[40:48] = struct.pack("<Q", first)
    h[48:56] = struct.pack("<Q", last)
    h[56:72] = DISK_GUID.bytes_le
    h[72:80] = struct.pack("<Q", entries_lba)
    h[80:84] = struct.pack("<I", 128)
    h[84:88] = struct.pack("<I", 128)
    h[88:92] = struct.pack("<I", crc_e)
    crc_h = zlib.crc32(bytes(h[0:92])) & 0xFFFFFFFF
    h[16:20] = struct.pack("<I", crc_h)
    return bytes(h), crc_h


def fixture(s):
    L = DISK_BYTES // s - 1
    A = 16384 // s
    M = 1024 * 1024 // s
    first, last = 2 + A, L - 1 - A
    esp = (M, M + 512 * M - 1)
    neofs_first = 513 * M
    E = ((L - A) // M) * M - 1
    blocks = (E + 1 - neofs_first) * s // 4096
    array = bytearray(16384)
    array[0:128] = entry(ESP_TYPE, ESP_GUID, esp[0], esp[1], 0, "EFI System")
    array[128:256] = entry(NEOFS_TYPE, NEOFS_GUID, neofs_first, E, 0, "LogansOS")
    crc_e = zlib.crc32(bytes(array)) & 0xFFFFFFFF
    primary, crc_h1 = header(s, 1, L, first, last, 2, crc_e)
    backup, crc_h2 = header(s, L, 1, first, last, L - A, crc_e)
    mbr = bytearray(s)
    mbr[446] = 0x00
    mbr[447:450] = bytes([0x00, 0x02, 0x00])
    mbr[450] = 0xEE
    mbr[451:454] = bytes([0xFF, 0xFF, 0xFF])
    mbr[454:458] = struct.pack("<I", 1)
    mbr[458:462] = struct.pack("<I", min(L, 0xFFFFFFFF))
    mbr[510:512] = b"\x55\xaa"
    return dict(s=s, L=L, A=A, M=M, first=first, last=last, esp=esp,
                neofs=(neofs_first, E), blocks=blocks, crc_e=crc_e,
                crc_h1=crc_h1, crc_h2=crc_h2, mbr=bytes(mbr),
                primary=primary, backup=backup,
                e1=bytes(array[0:128]), e2=bytes(array[128:256]))


def sparse(name, data):
    pairs = ", ".join(f"({i}, 0x{b:02x})" for i, b in enumerate(data) if b)
    return f"    pub const {name}: &[(usize, u8)] = &[{pairs}];\n"


def module(f):
    out = f"pub mod s{f['s']} {{\n"
    for key in ("s", "L", "A", "M", "first", "last", "blocks"):
        out += f"    pub const {key.upper()}: u64 = {f[key]};\n"
    out += f"    pub const ESP: (u64, u64) = ({f['esp'][0]}, {f['esp'][1]});\n"
    out += f"    pub const NEOFS: (u64, u64) = ({f['neofs'][0]}, {f['neofs'][1]});\n"
    for key in ("crc_e", "crc_h1", "crc_h2"):
        out += f"    pub const {key.upper()}: u32 = 0x{f[key]:08x};\n"
    out += sparse("MBR", f["mbr"])
    out += sparse("PRIMARY_HEADER", f["primary"])
    out += sparse("BACKUP_HEADER", f["backup"])
    out += sparse("ENTRY1", f["e1"])
    out += sparse("ENTRY2", f["e2"])
    return out + "}\n"


HEAD = """// SPDX-License-Identifier: MPL-2.0
//! GENERATED by fixtures/gpt_oracle.py from the THINK's §4.4 table, with
//! CRCs from Python's zlib.crc32. Do not edit by hand; re-run the script.
//! Every non-zero byte of LBA 0, both headers and entries 1-2 of a 4 GiB
//! disk, as (offset, byte).
#![allow(dead_code)]

pub const DISK_GUID: [u8; 16] = {disk};
pub const ESP_GUID: [u8; 16] = {esp};
pub const NEOFS_GUID: [u8; 16] = {neofs};

"""


def arr(g):
    return "[" + ", ".join(f"0x{b:02x}" for b in g.bytes_le) + "]"


if __name__ == "__main__":
    text = HEAD.format(disk=arr(DISK_GUID), esp=arr(ESP_GUID), neofs=arr(NEOFS_GUID))
    text += module(fixture(512)) + "\n" + module(fixture(4096))
    with open("../src/gpt_oracle.rs", "w") as fh:
        fh.write(text)
    for s in (512, 4096):
        f = fixture(s)
        print(s, f["L"], f["first"], f["last"], f["esp"], f["neofs"], f["blocks"],
              hex(f["crc_e"]), hex(f["crc_h1"]), hex(f["crc_h2"]))
