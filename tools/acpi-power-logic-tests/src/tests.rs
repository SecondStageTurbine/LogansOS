fn oracle(name: &str) -> String {
    fs::read_to_string(
        Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("fixtures")
            .join(name),
    )
    .unwrap()
}

/// A register in `fadt-oracle.txt`: `space:width:address` (hex), or `-`.
fn oracle_reg(s: &str) -> Option<(u8, u8, u64)> {
    if s == "-" {
        return None;
    }
    let v: Vec<u64> = s
        .split(':')
        .map(|x| u64::from_str_radix(x, 16).unwrap())
        .collect();
    Some((v[0] as u8, v[1] as u8, v[2]))
}

/// One row of `fixtures/fadt-oracle.txt`, generated by `gen-fadt-oracle.py`
/// from ACPICA's `iasl -d` disassembly of each set's FACP.
struct FadtRow {
    set: String,
    hex: Vec<u64>,
    regs: [Option<(u8, u8, u64)>; 8],
}

fn fadt_oracle() -> Vec<FadtRow> {
    oracle("fadt-oracle.txt")
        .lines()
        .filter(|l| !l.starts_with('#'))
        .map(|l| {
            let c: Vec<&str> = l.split_whitespace().collect();
            assert_eq!(c.len(), 19, "{l}");
            let h = |i: usize| u64::from_str_radix(c[i], 16).unwrap();
            FadtRow {
                set: c[0].to_string(),
                // revision flags smi_cmd acpi_enable pm1_evt_len pm1_cnt_len gpe0_len reset_space reset_addr reset_value
                hex: [1, 2, 3, 4, 7, 10, 12, 13, 14, 15]
                    .iter()
                    .map(|&i| h(i))
                    .collect(),
                // pm1a_evt pm1b_evt pm1a_cnt pm1b_cnt gpe0 sleep_control sleep_status pm_timer
                regs: [5, 6, 8, 9, 11, 16, 17, 18].map(|i| oracle_reg(c[i])),
            }
        })
        .collect()
}

/// What `fixtures/prototype-walk.txt` (the output of
/// `python3 -I docs/THINK-2026-10-27-ot90-s5-walk.py fixtures/acpi`, THINK
/// Appendix A) says about one set: each table's strict-pass result in the
/// prototype's order, and the decode.
struct ProtoSet {
    set: String,
    tables: Vec<(String, bool)>,
    /// (table name, NameOp offset, SLP_TYP a, SLP_TYP b).
    decode: (String, usize, u8, u8),
}

fn prototype_oracle() -> (Vec<ProtoSet>, String) {
    let text = oracle("prototype-walk.txt");
    let mut sets = Vec::new();
    let mut tables = Vec::new();
    let mut totals = String::new();
    for l in text.lines() {
        if let Some(rest) = l.strip_prefix("  ") {
            let c: Vec<&str> = rest.split_whitespace().collect();
            tables.push((c[1].to_string(), c[2] == "OK"));
        } else if let Some((set, r)) = l.split_once(" -> ") {
            // ('OK', 'dsdt.dat', '0x9a46', [7, 0])
            let r = r.replace(['(', ')', '[', ']', '\'', ','], " ");
            let c: Vec<&str> = r.split_whitespace().collect();
            assert_eq!(c[0], "OK", "{l}");
            let at = usize::from_str_radix(c[2].trim_start_matches("0x"), 16).unwrap();
            sets.push(ProtoSet {
                set: set.to_string(),
                tables: std::mem::take(&mut tables),
                decode: (
                    c[1].to_string(),
                    at,
                    c[3].parse().unwrap(),
                    c[4].parse().unwrap(),
                ),
            });
        } else {
            totals = l.to_string();
        }
    }
    (sets, totals)
}

/// The tables the prototype reads from a set, in its order: by file name, a
/// name starting `dsdt` or containing `ssdt` (case-folded), the DSDT first.
fn prototype_tables(set: &str) -> Vec<(String, Vec<u8>)> {
    let d = corpus_root().join(set);
    let mut t: Vec<(String, Vec<u8>)> = fs::read_dir(&d)
        .unwrap()
        .map(|e| e.unwrap().file_name().to_string_lossy().into_owned())
        .filter(|f| {
            let l = f.to_lowercase();
            l.starts_with("dsdt") || l.contains("ssdt")
        })
        .map(|f| (f.to_lowercase(), fs::read(d.join(&f)).unwrap()))
        .collect();
    t.sort_by(|a, b| (!a.0.starts_with("dsdt"), &a.0).cmp(&(!b.0.starts_with("dsdt"), &b.0)));
    t
}

#[test]
fn rust_walk_equals_the_prototype_on_every_set() {
    let (mut sets, totals) = prototype_oracle();
    assert_eq!(totals, "tables walked to end: 93/93; sets decoded: 10/10");
    sets.retain(|p| present(&p.set));
    let names: Vec<String> = corpus().into_iter().map(|s| s.name).collect();
    assert_eq!(
        names,
        sets.iter().map(|p| p.set.clone()).collect::<Vec<_>>()
    );
    for p in &sets {
        let tabs = prototype_tables(&p.set);
        let (r, per) = decode_s5_report(&refs(&tabs));
        let ours: Vec<(String, bool)> = tabs
            .iter()
            .zip(&per)
            .map(|((n, _), r)| (n.clone(), r.is_ok()))
            .collect();
        assert_eq!(ours, p.tables, "{}: per-table results", p.set);
        let f = r.unwrap_or_else(|e| panic!("{}: {e:?}", p.set));
        assert_eq!(
            (tabs[f.table].0.clone(), f.at, f.typ.a, f.typ.b),
            p.decode,
            "{}: the decode",
            p.set
        );
    }
}

/// The OS-visible decode: the DSDT and the XSDT-listed SSDTs only, in firmware
/// order. It must agree with the prototype's (which also reads the OptiPlex
/// Linux set's runtime-loaded SSDTs).
#[test]
fn xsdt_listed_tables_decode_the_same() {
    let (sets, _) = prototype_oracle();
    let corpus = corpus();
    assert_eq!(
        corpus.len(),
        sets.iter().filter(|p| present(&p.set)).count()
    );
    for s in &corpus {
        let p = sets
            .iter()
            .find(|p| p.set == s.name)
            .expect("an oracle row");
        let (_, _, a, b) = p.decode;
        assert_eq!(
            decode_s5(&refs(&s.listed)),
            Ok(SleepType { a, b }),
            "{}",
            s.name
        );
    }
}

#[test]
fn every_corpus_table_walks_to_its_end() {
    let (mut tables, mut sets) = (0, 0);
    for s in corpus() {
        let mut all = s.listed.clone();
        all.extend(s.dynamic.iter().cloned());
        let (r, per) = decode_s5_report(&refs(&all));
        assert!(r.is_ok(), "{}: {r:?}", s.name);
        for ((f, _), p) in all.iter().zip(&per) {
            assert_eq!(*p, Ok(()), "{} {f}", s.name);
        }
        tables += per.len();
        sets += 1;
    }
    // The prototype's oracle gives each set's table count, so the totals are
    // checked for exactly the sets in the tree (93 tables, 10 sets in full).
    let (want, _) = prototype_oracle();
    let want: Vec<&ProtoSet> = want.iter().filter(|p| present(&p.set)).collect();
    if want.len() == 10 {
        assert_eq!((tables, sets), (93, 10));
    }
    assert_eq!(
        (tables, sets),
        (want.iter().map(|p| p.tables.len()).sum(), want.len())
    );
}

#[test]
fn corpus_fadt_matches_the_acpica_disassembly() {
    let mut rows = fadt_oracle();
    rows.retain(|r| present(&r.set));
    let names: Vec<String> = corpus().into_iter().map(|s| s.name).collect();
    assert_eq!(
        names,
        rows.iter().map(|r| r.set.clone()).collect::<Vec<_>>()
    );
    let key = |g: Option<Gas>| g.map(|g| (g.space, g.bit_width, g.address));
    for (s, w) in corpus().iter().zip(&rows) {
        let f = parse_fadt(&s.fadt).unwrap();
        let got_hex = [
            f.revision as u64,
            f.flags as u64,
            f.smi_cmd as u64,
            f.acpi_enable as u64,
            f.pm1_evt_len as u64,
            f.pm1_cnt_len as u64,
            f.gpe0_len as u64,
            f.reset_reg.map_or(0xff, |g| g.space as u64),
            f.reset_reg.map_or(0, |g| g.address),
            f.reset_value as u64,
        ];
        assert_eq!(got_hex.to_vec(), w.hex, "{}", s.name);
        let got_regs = [
            f.pm1a_evt,
            f.pm1b_evt,
            f.pm1a_cnt,
            f.pm1b_cnt,
            f.gpe0,
            f.sleep_control,
            f.sleep_status,
        ]
        .map(key);
        assert_eq!(got_regs[..], w.regs[..7], "{}", s.name);
        // The PM timer, a SystemIO port, and its width from TMR_VAL_EXT.
        let (space, _, port) = w.regs[7].unwrap();
        assert_eq!(space, SPACE_SYSTEM_IO, "{}", s.name);
        let ext32 = w.hex[1] as u32 & TMR_VAL_EXT != 0;
        assert_eq!(f.pm_timer, Some((port, ext32)), "{}", s.name);
    }
}

fn s5_of(s: &Set) -> Result<SleepType, S5Error> {
    decode_s5(&refs(&s.listed))
}

#[test]
fn corpus_power_off_plans() {
    for s in corpus() {
        let f = parse_fadt(&s.fadt).unwrap();
        let plan = plan_power_off(&f, s5_of(&s), HHDM);
        assert_eq!(
            plan,
            PowerOffPlan::Legacy {
                pm1a: f.pm1a_cnt.unwrap(),
                pm1b: None,
                typ: s5_of(&s).unwrap(),
                pm1a_evt: split_block(f.pm1a_evt, f.pm1_evt_len),
                pm1b_evt: None,
                gpe0: split_block(f.gpe0, f.gpe0_len),
            },
            "{}",
            s.name
        );
        let PowerOffPlan::Legacy {
            pm1a_evt: Some(e),
            gpe0: Some(g),
            ..
        } = plan
        else {
            panic!("{}: no event blocks", s.name)
        };
        // The enable half follows the status half.
        assert_eq!(e.enable.address, e.status.address + 2, "{}", s.name);
        assert_eq!(
            g.enable.address,
            g.status.address + (f.gpe0_len / 2) as u64,
            "{}",
            s.name
        );
    }
}

#[test]
fn corpus_reset_chains() {
    use ResetStep::{Cf9, FadtRegister, Keyboard, TripleFault};
    for s in corpus() {
        let f = parse_fadt(&s.fadt).unwrap();
        let reg = f.reset_reg.unwrap();
        let first = FadtRegister {
            reg,
            value: f.reset_value,
        };
        let chain = reset_chain(&f, HHDM);
        if reg.address == 0xcf9 {
            assert_eq!(chain.steps(), [first, Keyboard, TripleFault], "{}", s.name);
        } else {
            // The OptiPlex and the AMD boxes write an SMI command to 0xB2.
            assert_eq!(reg.address, 0xb2, "{}", s.name);
            assert_eq!(
                chain.steps(),
                [first, Keyboard, Cf9, TripleFault],
                "{}",
                s.name
            );
        }
    }
}

