fn put(f: &mut [u8], at: usize, bytes: &[u8]) {
    f[at..at + bytes.len()].copy_from_slice(bytes);
}

fn gas_bytes(space: u8, width: u8, addr: u64) -> [u8; 12] {
    let mut g = [0u8; 12];
    g[0] = space;
    g[1] = width;
    g[4..].copy_from_slice(&addr.to_le_bytes());
    g
}

/// A 276-byte revision-6 FADT laid out by hand.
fn fadt_v6() -> Vec<u8> {
    let mut f = vec![0u8; 276];
    put(&mut f, 0, b"FACP");
    put(&mut f, 4, &276u32.to_le_bytes());
    f[8] = 6;
    put(&mut f, 48, &0xb2u32.to_le_bytes()); // SMI_CMD
    f[52] = 0xa0; // ACPI_ENABLE
    put(&mut f, 56, &0x1800u32.to_le_bytes()); // PM1a_EVT_BLK
    put(&mut f, 64, &0x1804u32.to_le_bytes()); // PM1a_CNT_BLK
    put(&mut f, 80, &0x1860u32.to_le_bytes()); // GPE0_BLK
    f[88] = 4; // PM1_EVT_LEN
    f[89] = 2; // PM1_CNT_LEN
    f[92] = 32; // GPE0_BLK_LEN
    put(&mut f, 76, &0x1808u32.to_le_bytes()); // PM_TMR_BLK
    f[91] = 4; // PM_TMR_LEN
    put(&mut f, 112, &(RESET_REG_SUP | (1 << 21)).to_le_bytes());
    put(&mut f, 116, &gas_bytes(1, 8, 0xcf9)); // RESET_REG
    f[128] = 0x06; // RESET_VALUE
    put(&mut f, 172, &gas_bytes(1, 16, 0x1804)); // X_PM1a_CNT_BLK
    put(&mut f, 220, &gas_bytes(1, 0, 0x1860)); // X_GPE0_BLK, width 0 as on the HP
    f
}

#[test]
fn fadt_fields_at_their_offsets() {
    let f = parse_fadt(&fadt_v6()).unwrap();
    assert_eq!(
        f,
        FadtPower {
            revision: 6,
            flags: RESET_REG_SUP | (1 << 21),
            smi_cmd: 0xb2,
            acpi_enable: 0xa0,
            pm1a_evt: Some(Gas::io(0x1800, 32)),
            pm1b_evt: None,
            pm1_evt_len: 4,
            pm1a_cnt: Some(Gas::io(0x1804, 16)),
            pm1b_cnt: None,
            pm1_cnt_len: 2,
            gpe0: Some(Gas {
                space: 1,
                bit_width: 0,
                bit_offset: 0,
                access_size: 0,
                address: 0x1860
            }),
            gpe0_len: 32,
            reset_reg: Some(Gas::io(0xcf9, 8)),
            reset_value: 0x06,
            sleep_control: None,
            sleep_status: None,
            pm_timer: Some((0x1808, false)),
        }
    );
}

#[test]
fn fadt_x_block_wins_over_the_32_bit_block() {
    let mut b = fadt_v6();
    put(
        &mut b,
        172,
        &gas_bytes(SPACE_SYSTEM_MEMORY, 16, 0xfed8_0804),
    );
    assert_eq!(
        parse_fadt(&b).unwrap().pm1a_cnt,
        Some(Gas {
            space: 0,
            bit_width: 16,
            bit_offset: 0,
            access_size: 0,
            address: 0xfed8_0804
        })
    );
    // An X_ block with address 0 falls back to the 32-bit one.
    put(&mut b, 172, &gas_bytes(SPACE_SYSTEM_MEMORY, 16, 0));
    assert_eq!(parse_fadt(&b).unwrap().pm1a_cnt, Some(Gas::io(0x1804, 16)));
}

#[test]
fn fadt_past_its_length_reads_as_zero() {
    // A revision-1 FADT is 116 bytes: no RESET_REG, no X_ blocks.
    let mut b = fadt_v6();
    put(&mut b, 4, &116u32.to_le_bytes());
    b[8] = 1;
    let f = parse_fadt(&b).unwrap();
    assert_eq!((f.reset_reg, f.reset_value), (None, 0));
    assert_eq!(
        f.pm1a_cnt,
        Some(Gas::io(0x1804, 16)),
        "the 32-bit block still counts"
    );
    // 32 bytes is 256 bits: the width saturates at 255, as ACPICA truncates it
    // (`AcpiTbInitGenericAddress`); GPE handling uses GPE0_BLK_LEN.
    assert_eq!(f.gpe0, Some(Gas::io(0x1860, 255)));
    // Too short to hold the flags, or not a FADT.
    put(&mut b, 4, &115u32.to_le_bytes());
    assert_eq!(parse_fadt(&b), None);
    assert_eq!(parse_fadt(&b"APIC\x74\0\0\0".repeat(20)), None);
    assert_eq!(parse_fadt(&fadt_v6()[..100]), None);
}

