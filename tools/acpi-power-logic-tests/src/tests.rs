fn walk_fault(r: Result<SleepType, S5Error>) -> Option<WalkFault> {
    match r {
        Err(S5Error::Walk { fault, .. }) => Some(fault),
        _ => None,
    }
}

#[test]
fn iasl_negatives_fail_closed() {
    let one = |f: &str| decode_s5(&[&fixture(f)]);
    // Janus #93: Method (\_S5) beside \_SB._S5.
    assert_eq!(walk_fault(one("janus.aml")), Some(WalkFault::MethodS5));
    // Janus #118: _S5 bytes in a Buffer payload; then in a String, and in a
    // Buffer inside a Package. None is a term the walk reaches.
    for f in ["bufpay.aml", "strpay.aml", "pkgpay.aml"] {
        assert_eq!(one(f), Err(S5Error::RootDefinitions(0)), "{f}");
    }
    // Scope (\_SB) { Name (_S5, ...) } and Device (DEV0) { Name (_S5, ...) }.
    assert_eq!(one("sbonly.aml"), Err(S5Error::RootDefinitions(0)));
    assert_eq!(one("indev.aml"), Err(S5Error::RootDefinitions(0)));
    // If (One) { Name (_S5, ...) }.
    assert_eq!(walk_fault(one("inif.aml")), Some(WalkFault::ConditionalS5));
    // Name (_S5, Package (2) { 8, 0 }).
    assert_eq!(one("badtyp.aml"), Err(S5Error::BadPackage));
}

#[test]
fn iasl_positives() {
    // Scope (\_SB) { Name (\_S5, ...) }: an absolute path, bound at the root.
    assert_eq!(
        decode_s5(&[&fixture("abs.aml")]),
        Ok(SleepType { a: 7, b: 0 })
    );
    // No _S5 in the DSDT; a root _S5 in an SSDT.
    let (d, s) = (fixture("dsdtempty.aml"), fixture("ssdtroot.aml"));
    assert_eq!(decode_s5(&[&d, &s]), Ok(SleepType { a: 5, b: 0 }));
}

