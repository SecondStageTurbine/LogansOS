#[test]
fn hw_reduced_sleep_registers_need_their_acpi_geometry() {
    // #140 F1 (Janus): his 276-byte FACP, HW_REDUCED_ACPI set, SLEEP_CONTROL
    // at 244 = {SystemIO, width 16, bit offset 8, access size 0, 0x1804},
    // SLEEP_STATUS at 256 = {SystemIO, width 8, offset 0, 0x1800}; \_S5 is 7/0.
    // The plan used to be HwReduced with value 0x3c; a raw byte write can't
    // honour a 16-bit field at bit 8, so it must be refused.
    let mut b = fadt_v6();
    put(&mut b, 112, &(RESET_REG_SUP | (1 << 20)).to_le_bytes());
    put(
        &mut b,
        244,
        &[0x01, 0x10, 0x08, 0x00, 0x04, 0x18, 0, 0, 0, 0, 0, 0],
    );
    put(
        &mut b,
        256,
        &[0x01, 0x08, 0x00, 0x00, 0x00, 0x18, 0, 0, 0, 0, 0, 0],
    );
    let f = parse_fadt(&b).unwrap();
    assert!(f.hw_reduced());
    assert_eq!(
        f.sleep_control,
        Some(Gas {
            space: SPACE_SYSTEM_IO,
            bit_width: 16,
            bit_offset: 8,
            access_size: 0,
            address: 0x1804,
        })
    );
    assert_eq!(
        plan_power_off(&f, SEVEN, HHDM),
        PowerOffPlan::SafeToTurnOff(NoPowerOff::UnsupportedSleepRegisters)
    );
    // Each geometry field alone, on either register: width, offset, access size.
    let good = Gas::io(0x1804, 8);
    for bad in [
        Gas {
            bit_width: 16,
            ..good
        },
        Gas {
            bit_width: 0,
            ..good
        },
        Gas {
            bit_offset: 1,
            ..good
        },
        Gas {
            access_size: 2,
            ..good
        },
        Gas {
            access_size: 4,
            ..good
        },
    ] {
        let mut c = f;
        c.sleep_control = Some(bad);
        c.sleep_status = Some(Gas::io(0x1800, 8));
        assert_eq!(
            plan_power_off(&c, SEVEN, HHDM),
            PowerOffPlan::SafeToTurnOff(NoPowerOff::UnsupportedSleepRegisters),
            "control {bad:?}"
        );
        c.sleep_control = Some(good);
        c.sleep_status = Some(Gas {
            address: 0x1800,
            ..bad
        });
        assert_eq!(
            plan_power_off(&c, SEVEN, HHDM),
            PowerOffPlan::SafeToTurnOff(NoPowerOff::UnsupportedSleepRegisters),
            "status {bad:?}"
        );
    }
    // The supported geometry: 8 bits at offset 0, access size 0 or 1.
    let mut ok = f;
    ok.sleep_control = Some(good);
    ok.sleep_status = Some(Gas {
        access_size: 1,
        ..Gas::io(0x1800, 8)
    });
    assert_eq!(
        plan_power_off(&ok, SEVEN, HHDM),
        PowerOffPlan::HwReduced {
            control: good,
            status: Gas {
                access_size: 1,
                ..Gas::io(0x1800, 8)
            },
            value: 0x3c
        }
    );
}
