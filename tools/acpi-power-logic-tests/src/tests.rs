/// A deterministic mutation sweep over a real DSDT: truncations and byte
/// flips never panic, and a decode that still succeeds stays in range.
#[test]
fn mutated_tables_never_panic() {
    let Some(set) = corpus().into_iter().find(|s| s.name.starts_with("zenbook")) else {
        std::eprintln!("SKIP: the Zenbook DSDT (a real-machine set) is absent");
        return;
    };
    let dsdt = set.listed[0].1.clone();
    let mut x: u64 = 0x9e37_79b9_7f4a_7c15;
    let mut next = || {
        x ^= x << 13;
        x ^= x >> 7;
        x ^= x << 17;
        x
    };
    for _ in 0..300 {
        let mut t = dsdt.clone();
        let cut = 36 + (next() as usize % (t.len() - 36));
        if next() % 2 == 0 {
            t.truncate(cut);
        } else {
            t[cut] = next() as u8;
        }
        if let Ok(typ) = decode_s5(&[&t]) {
            assert!(typ.a <= 7 && typ.b <= 7);
        }
    }
}

