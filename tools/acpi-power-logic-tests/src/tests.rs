struct Set {
    name: String,
    fadt: Vec<u8>,
    /// The DSDT, then the XSDT-listed SSDTs in firmware order.
    listed: Vec<(String, Vec<u8>)>,
    /// SSDTs firmware installed at run time (`dynamic-*`, never XSDT-listed).
    dynamic: Vec<(String, Vec<u8>)>,
}

fn corpus_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../fixtures/acpi")
}

fn numeric_suffix(name: &str) -> u64 {
    let stem = name.split('.').next().unwrap_or(name);
    let digits: String = stem
        .chars()
        .rev()
        .take_while(char::is_ascii_digit)
        .collect();
    digits
        .chars()
        .rev()
        .collect::<String>()
        .parse()
        .unwrap_or(0)
}

/// Tables by header signature, never by file name (the corpus README).
fn corpus() -> Vec<Set> {
    let mut dirs: Vec<PathBuf> = fs::read_dir(corpus_root())
        .unwrap()
        .map(|e| e.unwrap().path())
        .filter(|p| p.is_dir())
        .collect();
    dirs.sort();
    dirs.iter()
        .map(|d| {
            let mut files: Vec<String> = fs::read_dir(d)
                .unwrap()
                .map(|e| e.unwrap().file_name().to_string_lossy().into_owned())
                .collect();
            files.sort();
            let (mut fadt, mut dsdt, mut ssdts) = (None, None, Vec::new());
            for f in files {
                let b = fs::read(d.join(&f)).unwrap();
                match b.get(..4) {
                    Some(b"FACP") => fadt = Some(b),
                    Some(b"DSDT") => dsdt = Some((f, b)),
                    Some(b"SSDT") => ssdts.push((f, b)),
                    _ => {}
                }
            }
            ssdts.sort_by_key(|(f, _)| (numeric_suffix(f), f.clone()));
            let (dynamic, static_): (Vec<_>, Vec<_>) = ssdts
                .into_iter()
                .partition(|(f, _)| f.starts_with("dynamic-"));
            let mut listed = vec![dsdt.expect("a DSDT")];
            listed.extend(static_);
            Set {
                name: d.file_name().unwrap().to_string_lossy().into_owned(),
                fadt: fadt.expect("a FACP"),
                listed,
                dynamic,
            }
        })
        .collect()
}

/// Whether a corpus set is in the tree. The real-machine sets are kept in the
/// private repo only; a public checkout carries just the QEMU sets, so the
/// oracle rows of absent sets are skipped and whole-corpus totals are checked
/// only when every set is present. The QEMU sets may never be absent.
fn present(set: &str) -> bool {
    let here = corpus_root().join(set).is_dir();
    assert!(here || !set.starts_with("qemu-"), "QEMU set {set} missing");
    if !here {
        std::eprintln!("note: real-machine corpus set {set} absent (kept in the private repo)");
    }
    here
}

fn refs(t: &[(String, Vec<u8>)]) -> Vec<&[u8]> {
    t.iter().map(|(_, b)| b.as_slice()).collect()
}

