    assert_eq!(
        plan_power_off(&far, Ok(SleepType { a: 7, b: 0 }), HHDM),
        PowerOffPlan::SafeToTurnOff(NoPowerOff::UnsupportedPm1)
    );
    // An event block that would cross 0xFFFF is dropped from the plan.
    assert_eq!(split_block(Some(Gas::io(0xfff0, 0)), 32), None);
