// iter7: the cross-thread (CURBE) argument payload lives in its own GGTT page,
// distinct from state/kernel/lhs/rhs/output/seqno. MEDIA_CURBE_LOAD reads the
// stateless-A64 pointer payload from here (Dynamic State Base = 0, so the data
// start address is this absolute GGTT offset).
pub const GGTT_CURBE_BASE: u64 = 0x0013_4000;

