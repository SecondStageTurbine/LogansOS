// Finalizer-built EU kernels (Phase 6 BUILD-4a finalizer lane).
//
// Both blobs below are emitted by the pinned, reproducible Intel Gen9 finalizer
// toolchain in `tools/intel-gen9-finalizer/` (IGC `igc-1.0.17193.4` +
// compute-runtime `24.26.30049.6`, which rates Skylake/Kaby Lake = Production).
// `tools/intel-gen9-finalizer/build-kernels.sh` compiles the checked-in OpenCL-C
// sources with `ocloc compile -device skl`, extracts the bare EU instruction
// stream from the zebin `.text.<kernel>` section, and disassembles it with
// `ocloc disasm` — the disassembly is the independent byte oracle, checked in as
// `intel_gen9_kernels/<name>.gen9.asm`. Per-source/per-blob sha256 provenance and
// the one-command regenerate+diff path are in `intel_gen9_kernels/README.md`.
//
// These replace the earlier un-finalized blobs: the Add was an ASCII *placeholder*
// (never compiled), and the no-op was *hand-laid* from the EU ISA. The iter5
// Stage-B bisect (no-op hung byte-identically to the Add) is exactly the
// "regenerate with the real finalizer" trigger the kernel README named.
//
// Each native Gen9 instruction is 16 bytes (four little-endian DWords); the
// finalizer pads the `.text` section past the terminating EOT `send` with
// `illegal` ops (the trailing zero bytes), which the thread never reaches.

/// EOT send message descriptor (DW3) the finalizer emits for the spawner
/// End-Of-Thread on Gen9: EOT (bit 31) | mlen 1 (bits 28:25) | root-thread-end
/// control (0x10). `ocloc disasm` renders this as `send ... 0x27 0x02000010 {EOT}`
/// (the `0x27` is the extended descriptor; the EOT bit lives in this DW3).
const EU_EOT_SEND_DESC: u32 = 0x8200_0010;

/// True if `blob` contains an EOT `send` (its DW3 == [`EU_EOT_SEND_DESC`]) at any
/// native-instruction DWord boundary. The terminating EOT is no longer the array
/// tail (the finalizer pads past it), so this scans rather than checking a fixed
/// offset.
const fn blob_has_eot_send(blob: &[u8]) -> bool {
    let mut i = 0;
    while i + 4 <= blob.len() {
        let dw = u32::from_le_bytes([blob[i], blob[i + 1], blob[i + 2], blob[i + 3]]);
        if dw == EU_EOT_SEND_DESC {
            return true;
        }
        i += 4;
    }
    false
}

