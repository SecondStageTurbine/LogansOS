// --- Cross-thread argument ABI (independent oracle: `blur.gen9.zeinfo`) ----
// src@32, dst@40, weights@48 (stateless A64 ptrs); width@56, height@60, stride@64,
// radius@68, axis@72 (byvalue u32); enqueued_local_size@76 (span ends at 88 =>
// ceil(88/32)=3 GRF cross-thread). Per-thread local_id = 192 B = 6 GRF (SIMD32,
// 2-D: local_id.x r1/r2 + local_id.y r3/r4). No slm_size / no barrier_count keys.
pub const BLUR_OFF_ARG_SRC: usize = 32;
pub const BLUR_OFF_ARG_DST: usize = 40;
pub const BLUR_OFF_ARG_WEIGHTS: usize = 48;
pub const BLUR_OFF_WIDTH: usize = 56;
pub const BLUR_OFF_HEIGHT: usize = 60;
pub const BLUR_OFF_STRIDE: usize = 64;
pub const BLUR_OFF_RADIUS: usize = 68;
pub const BLUR_OFF_AXIS: usize = 72;
pub const BLUR_OFF_ENQUEUED_LOCAL_SIZE: usize = 76;
/// IDD Cross-Thread Constant Data Read Length: span [0,88) -> ceil(88/32) = 3 GRF
/// (the same 3-GRF cross-thread block as the Add/matmul; only the fields differ).
pub const BLUR_CROSS_THREAD_GRF: u32 = 3;
/// SLM bytes the blur needs: 0 (no `slm_size` key in the zeinfo; ADR-077 v2 §4.5).
pub const BLUR_SLM_BYTES: u32 = 0;
/// Workgroup barriers the blur needs: 0 (no `barrier_count` key in the zeinfo).
pub const BLUR_BARRIER_COUNT: u32 = 0;
/// Pass selector values the driver programs into the `axis` byvalue arg (@72).
pub const BLUR_AXIS_H: u32 = 0;
pub const BLUR_AXIS_V: u32 = 1;

/// Gen9 `INTERFACE_DESCRIPTOR_DATA` for the pinned blur kernel. The thread
/// count is load-bearing: PRM Vol. 2a requires it to equal
/// `(ThreadDepthMax+1) * (ThreadHeightMax+1) * (ThreadWidthMax+1)` from the
/// walker. Slice 4 packs its eight SIMD32 hardware threads along walker-width,
/// matching Mesa iris' Gen9 convention, so DW6 must be 8 (not the Phase-6
/// one-thread value).
pub const fn blur_interface_descriptor_dwords() -> [u32; 8] {
    [
        GGTT_KERNEL_BASE as u32,
        0,
        0,
        0,
        0,
        CURBE_PER_THREAD_GRF << 16,
        BLUR_THREADS_PER_GROUP,
        BLUR_CROSS_THREAD_GRF,
    ]
}

/// Build the 96-byte stateless-A64 cross-thread payload for ONE blur pass. `src`/
/// `dst`/`weights` are absolute GPU virtual addresses; `axis` = [`BLUR_AXIS_H`] or
/// [`BLUR_AXIS_V`]. Layout per `blur.gen9.zeinfo`. The 2-D NDRange is (width,
/// height, 1). Padding stays zero.
// The eight parameters ARE the kernel's stateless-A64 ABI (three pointers + five
// byvalue scalars, `blur.gen9.zeinfo`); grouping them would only hide the layout
// the payload must reproduce byte-for-byte.
#[allow(clippy::too_many_arguments)]
pub fn build_blur_curbe_payload(
    src: u64,
    dst: u64,
    weights: u64,
    width: u32,
    height: u32,
    stride: u32,
    radius: u32,
    axis: u32,
) -> [u8; CURBE_PAYLOAD_BYTES] {
    let mut p = [0u8; CURBE_PAYLOAD_BYTES];
    let local = [BLUR_LOCAL_SIZE_X, BLUR_LOCAL_SIZE_Y, 1];
    write_u32x3(&mut p, CURBE_OFF_LOCAL_SIZE, local); // @12
    p[BLUR_OFF_ARG_SRC..BLUR_OFF_ARG_SRC + 8].copy_from_slice(&src.to_le_bytes());
    p[BLUR_OFF_ARG_DST..BLUR_OFF_ARG_DST + 8].copy_from_slice(&dst.to_le_bytes());
    p[BLUR_OFF_ARG_WEIGHTS..BLUR_OFF_ARG_WEIGHTS + 8].copy_from_slice(&weights.to_le_bytes());
    p[BLUR_OFF_WIDTH..BLUR_OFF_WIDTH + 4].copy_from_slice(&width.to_le_bytes());
    p[BLUR_OFF_HEIGHT..BLUR_OFF_HEIGHT + 4].copy_from_slice(&height.to_le_bytes());
    p[BLUR_OFF_STRIDE..BLUR_OFF_STRIDE + 4].copy_from_slice(&stride.to_le_bytes());
    p[BLUR_OFF_RADIUS..BLUR_OFF_RADIUS + 4].copy_from_slice(&radius.to_le_bytes());
    p[BLUR_OFF_AXIS..BLUR_OFF_AXIS + 4].copy_from_slice(&axis.to_le_bytes());
    write_u32x3(&mut p, BLUR_OFF_ENQUEUED_LOCAL_SIZE, local); // @76
    p
}

// ---------------------------------------------------------------------------
// amendment 6 — the PRM-derived inter-pass command-byte oracle + the two-pass
// blur command batch (ADR-077 v2 §4.4).
//
// Pass V must observe Pass H's A64 writes to `mid`. On Gen9 the transition is a
// PIPE_CONTROL with CS-Stall + DC-Flush placed BETWEEN the two GPGPU_WALKER
// dispatches — NOT MOCS (amendment 6: MOCS is a cacheability index, not a
// barrier). The command DWords come from the Kaby Lake PRM Vol 2a (PIPE_CONTROL),
// the same authority this file already cites, reusing the silicon-proven
// constants the Phase-6 Add path landed (PIPE_CONTROL_6DW, CS-stall bit20 +
// DC-flush bit5 = PIPE_CONTROL_FLUSH_STALL). The MOCS governing the blur's
// stateless-A64 traffic is the Stateless Data Port Access MOCS in
// STATE_BASE_ADDRESS DW3 (= 0, uncached) — an uncached-stateless policy makes
// H's writes memory-visible; the PIPE_CONTROL provides the ordering.
//
// The oracle is asserted by a HAND-LAID byte fixture in the host suite (the
// ADR-028 discipline: bytes computed independent of this encoder), so a wrong bit
// here fails the KAT even though QEMU cannot run the Gen9 EU.

/// The exact 6-DWord inter-pass PIPE_CONTROL (H->V dataport coherence barrier).
pub const BLUR_INTERPASS_PIPE_CONTROL: [u32; 6] = [
    PIPE_CONTROL_6DW,         // DW0 0x7a00_0004  PIPE_CONTROL, 6 DWords
    PIPE_CONTROL_FLUSH_STALL, // DW1 0x0010_0020  CS Stall (bit20) + DC Flush (bit5)
    0,                        // DW2 Address low  (no post-sync write here)
    0,                        // DW3 Address high
    0,                        // DW4 Immediate low
    0,                        // DW5 Immediate high
];

/// The Stateless Data Port Access MOCS index the blur programs (STATE_BASE_ADDRESS
/// DW3) — 0 = uncached, the bring-up-safe policy under which the inter-pass
/// PIPE_CONTROL is a sufficient H->V coherence transition (amendment 6).
pub const BLUR_STATELESS_DATAPORT_MOCS: u32 = 0;

/// Emit the inter-pass PIPE_CONTROL barrier (24 bytes) — the amendment-6
/// command-byte deliverable, asserted against the hand-laid PRM byte fixture.
pub fn encode_blur_interpass_barrier(dst: &mut [u8]) -> Option<usize> {
    if dst.len() < 24 {
        return None;
    }
    for (idx, dw) in BLUR_INTERPASS_PIPE_CONTROL.iter().enumerate() {
        let base = idx * 4;
        dst[base..base + 4].copy_from_slice(&dw.to_le_bytes());
    }
    Some(24)
}

// The two-pass blur batch: one 92-DWord command stream —
//   PIPELINE_SELECT(1) + PIPE_CONTROL(6) + STATE_BASE_ADDRESS(19) + PIPE_CONTROL(6)
//   + MEDIA_VFE_STATE(9) + MEDIA_INTERFACE_DESCRIPTOR_LOAD(4) + MEDIA_STATE_FLUSH(2)
//   + GPGPU_WALKER_H(15) + PIPE_CONTROL_interpass(6) + MEDIA_STATE_FLUSH(2)
//   + GPGPU_WALKER_V(15) + PIPE_CONTROL_seqno(6) + MI_BATCH_BUFFER_END(1) = 92.
// The two walkers point at two cross-thread heaps (H: src->mid axis=0; V:
// mid->dst axis=1); the inter-pass PIPE_CONTROL is what makes V observe H.
// SILICON-UNPROVEN under QEMU (accel-intel is bare-metal-only): the 2-D walker
// geometry + real EU execution are the Slice-4 gate (ADR-077 v2 §8 Slice 4). This
// encoder is host-proven for STRUCTURE (opcodes, the inter-pass barrier position,
// the trailing seqno) + the command-byte oracle.
pub const BLUR_BATCH_DWORDS: usize = 92;
pub const BLUR_BATCH_BYTES: usize = BLUR_BATCH_DWORDS * 4;
pub const BLUR_H_BATCH_DWORDS: usize = 69;
pub const BLUR_H_BATCH_BYTES: usize = BLUR_H_BATCH_DWORDS * 4;

/// GGTT bases for the blur's buffers (BUILD-4a legacy-ring layout; Slice 4 binds
/// the real arena DmaBuffers). `curbe_h`/`curbe_v` are the two per-pass
/// cross-thread heaps. Distinct pages so H and V read independent payloads.
#[derive(Copy, Clone, Eq, PartialEq, Debug)]
pub struct BlurBatchLayout {
    pub state_base: u64,
    pub kernel_base: u64,
    pub seqno_base: u64,
    pub curbe_h_base: u64,
    pub curbe_v_base: u64,
}

/// SIMD32 2-D group geometry: X groups = ceil(width/32), Y groups = ceil(height/8)
/// (ADR-077 v2 §1.4: a 32x8 work-group). Returned as (x_groups, y_groups).
pub const fn blur_group_dims(width: u32, height: u32) -> (u32, u32) {
    (
        width.div_ceil(BLUR_LOCAL_SIZE_X),
        height.div_ceil(BLUR_LOCAL_SIZE_Y),
    )
}

fn write_blur_walker(out: &mut [u32], i: usize, curbe_base: u64, x_groups: u32, y_groups: u32) {
    // 2-D GPGPU_WALKER: Indirect Data heap [cross 96B][per-thread local_id 192B]
    // at curbe_base; SIMD32; thread-group dims (x_groups, y_groups, 1). Masks full
    // — partial edge groups are handled by the kernel's up-front x/y bounds guard
    // (ADR-077 v2 §1.4, amendment 2), not by trimming the walker mask.
    out[i] = GPGPU_WALKER_15DW;
    out[i + 2] = BLUR_WALKER_INDIRECT_DATA_LENGTH;
    out[i + 3] = curbe_base as u32;
    // ThreadWidthCounterMaximum stores N-1 in bits [5:0]. The SIMD-size field
    // remains SIMD32 in bits [31:30]. Eight rows therefore encode as 7.
    out[i + 4] = GPGPU_WALKER_SIMD32_THREADCOUNT | (BLUR_THREADS_PER_GROUP - 1);
    out[i + 7] = x_groups;
    out[i + 10] = y_groups;
    out[i + 12] = 1;
    out[i + 13] = GPGPU_WALKER_EXEC_MASK_FULL;
    out[i + 14] = GPGPU_WALKER_EXEC_MASK_FULL;
}

/// Build the two-pass blur command batch into `out` (>= [`BLUR_BATCH_DWORDS`]).
pub fn build_blur_batch(
    seqno: u32,
    width: u32,
    height: u32,
    layout: BlurBatchLayout,
    out: &mut [u32],
) -> usize {
    let sba = state_base_address_dwords();
    let (xg, yg) = blur_group_dims(width, height);
    let mut i = 0usize;

    out[i] = PIPELINE_SELECT_GPGPU;
    i += 1;

    out[i] = PIPE_CONTROL_6DW;
    out[i + 1] = PIPE_CONTROL_FLUSH_STALL;
    i += 6;

    let mut j = 0;
    while j < sba.len() {
        out[i + j] = sba[j];
        j += 1;
    }
    i += sba.len();

    out[i] = PIPE_CONTROL_6DW;
    out[i + 1] = PIPE_CONTROL_SBA_INVALIDATE;
    i += 6;

    out[i] = MEDIA_VFE_STATE_9DW;
    out[i + 3] = MEDIA_VFE_STATE_DW3;
    out[i + 5] = BLUR_MEDIA_VFE_STATE_DW5;
    i += 9;

    out[i] = MEDIA_INTERFACE_DESCRIPTOR_LOAD_4DW;
    out[i + 2] = INTERFACE_DESCRIPTOR_TOTAL_LENGTH;
    out[i + 3] = layout.state_base as u32;
    i += 4;

    out[i] = MEDIA_STATE_FLUSH_2DW;
    i += 2;

    // Pass H (src -> mid, axis=0): the H cross-thread heap.
    write_blur_walker(out, i, layout.curbe_h_base, xg, yg);
    i += 15;

    // The inter-pass coherence barrier (amendment 6): V must observe H's writes.
    out[i] = BLUR_INTERPASS_PIPE_CONTROL[0];
    out[i + 1] = BLUR_INTERPASS_PIPE_CONTROL[1];
    i += 6;

    // Re-flush the descriptor state before the second walker.
    out[i] = MEDIA_STATE_FLUSH_2DW;
    i += 2;

    // Pass V (mid -> dst, axis=1): the V cross-thread heap.
    write_blur_walker(out, i, layout.curbe_v_base, xg, yg);
    i += 15;

    // Trailing PIPE_CONTROL: post-sync immediate write of the completion seqno +
    // DC flush so the dst A64 writes are CPU-coherent before the seqno lands.
    out[i] = PIPE_CONTROL_6DW;
    out[i + 1] = PIPE_CONTROL_SEQNO_WRITE;
    out[i + 2] = layout.seqno_base as u32;
    out[i + 3] = (layout.seqno_base >> 32) as u32;
    out[i + 4] = seqno;
    i += 6;

    out[i] = MI_BATCH_BUFFER_END;
    i += 1;

    i
}

/// Build the separate H-only diagnostic run. It uses the identical descriptor,
/// kernel, local-id payload, and H walker as the primary batch, then retires a
/// seqno. Reading `mid` after this batch cannot perturb the untouched H->V run.
pub fn build_blur_h_batch(
    seqno: u32,
    width: u32,
    height: u32,
    layout: BlurBatchLayout,
    out: &mut [u32],
) -> usize {
    if out.len() < BLUR_H_BATCH_DWORDS {
        return 0;
    }
    let sba = state_base_address_dwords();
    let (xg, yg) = blur_group_dims(width, height);
    let mut i = 0usize;
    out[i] = PIPELINE_SELECT_GPGPU;
    i += 1;
    out[i] = PIPE_CONTROL_6DW;
    out[i + 1] = PIPE_CONTROL_FLUSH_STALL;
    i += 6;
    out[i..i + sba.len()].copy_from_slice(&sba);
    i += sba.len();
    out[i] = PIPE_CONTROL_6DW;
    out[i + 1] = PIPE_CONTROL_SBA_INVALIDATE;
    i += 6;
    out[i] = MEDIA_VFE_STATE_9DW;
    out[i + 3] = MEDIA_VFE_STATE_DW3;
    out[i + 5] = BLUR_MEDIA_VFE_STATE_DW5;
    i += 9;
    out[i] = MEDIA_INTERFACE_DESCRIPTOR_LOAD_4DW;
    out[i + 2] = INTERFACE_DESCRIPTOR_TOTAL_LENGTH;
    out[i + 3] = layout.state_base as u32;
    i += 4;
    out[i] = MEDIA_STATE_FLUSH_2DW;
    i += 2;
    write_blur_walker(out, i, layout.curbe_h_base, xg, yg);
    i += 15;
    out[i] = PIPE_CONTROL_6DW;
    out[i + 1] = PIPE_CONTROL_SEQNO_WRITE;
    out[i + 2] = layout.seqno_base as u32;
    out[i + 3] = (layout.seqno_base >> 32) as u32;
    out[i + 4] = seqno;
    i += 6;
    out[i] = MI_BATCH_BUFFER_END;
    i += 1;
    i
}

pub fn encode_blur_h_batch(
    dst: &mut [u8],
    seqno: u32,
    width: u32,
    height: u32,
    layout: BlurBatchLayout,
) -> Option<usize> {
    if dst.len() < BLUR_H_BATCH_BYTES {
        return None;
    }
    let mut dwords = [0u32; BLUR_H_BATCH_DWORDS];
    if build_blur_h_batch(seqno, width, height, layout, &mut dwords) != BLUR_H_BATCH_DWORDS {
        return None;
    }
    for (index, dword) in dwords.iter().enumerate() {
        dst[index * 4..index * 4 + 4].copy_from_slice(&dword.to_le_bytes());
    }
    Some(BLUR_H_BATCH_BYTES)
}

/// The DWord index (into the batch) where each fixed packet lands — the structure
/// oracle the host KAT asserts (two walkers, the inter-pass barrier strictly
/// between them). Derived from the fixed packet lengths above.
pub const BLUR_WALKER_H_DW: usize = 1 + 6 + STATE_BASE_ADDRESS_DWORDS + 6 + 9 + 4 + 2; // 47
pub const BLUR_VFE_STATE_DW: usize = 1 + 6 + STATE_BASE_ADDRESS_DWORDS + 6;
pub const BLUR_INTERPASS_PC_DW: usize = BLUR_WALKER_H_DW + 15; // 62
pub const BLUR_WALKER_V_DW: usize = BLUR_INTERPASS_PC_DW + 6 + 2; // 70

pub fn encode_blur_batch(
    dst: &mut [u8],
    seqno: u32,
    width: u32,
    height: u32,
    layout: BlurBatchLayout,
) -> Option<usize> {
    if dst.len() < BLUR_BATCH_BYTES {
        return None;
    }
    let mut dwords = [0u32; BLUR_BATCH_DWORDS];
    let len = build_blur_batch(seqno, width, height, layout, &mut dwords);
    if len != BLUR_BATCH_DWORDS {
        return None;
    }
    for (idx, dword) in dwords.iter().enumerate() {
        let base = idx * 4;
        dst[base..base + 4].copy_from_slice(&dword.to_le_bytes());
    }
    Some(BLUR_BATCH_BYTES)
}
