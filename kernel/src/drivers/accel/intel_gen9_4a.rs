const MI_BATCH_BUFFER_END: u32 = 0x0500_0000;
// PIPELINE_SELECT (1 DW): select GPGPU (low bits = 0x2) and set the Gen9 mask
// bits [9:8] for the two selection bits being written. Base opcode 0x6904_0000 |
// mask(0x3<<8) | GPGPU(0x2). (The pre-iter6 0x6904_3332 also force-enabled
// media-awake + DOP clock gating, which we don't want for a minimal dispatch.)
const PIPELINE_SELECT_GPGPU: u32 = 0x6904_0302;
const PIPE_CONTROL_6DW: u32 = 0x7a00_0004;
// CS-stall + DC flush before STATE_BASE_ADDRESS (DW1: bit20 CS Stall, bit5 DC Flush).
const PIPE_CONTROL_FLUSH_STALL: u32 = 0x0010_0020;
// Post-STATE_BASE_ADDRESS cache invalidate so the EU fetches code from the new
// Instruction Base instead of any stale cache (DW1: bit20 CS Stall, bit11
// Instruction Cache Invalidate, bit10 Texture Cache Invalidate, bit3 Constant
// Cache Invalidate, bit2 State Cache Invalidate). This directly targets the
// iter5 "instruction fetch stuck" (INSTDONE bit 21) signature.
const PIPE_CONTROL_SBA_INVALIDATE: u32 = (1 << 20) | (1 << 11) | (1 << 10) | (1 << 3) | (1 << 2);
const PIPE_CONTROL_SEQNO_WRITE: u32 = 0x0010_4024;
const MEDIA_VFE_STATE_9DW: u32 = 0x7000_0007;
// MEDIA_VFE_STATE DW3: Maximum Number of Threads [31:16] (bias of 1) | Number of
// URB Entries [15:8]. Gen8+ requires NumberofURBEntries = 2 (i965). Max threads
// programmed to the KBL GT2 device max (24 EU x 7 = 168 -> field = 167).
// `pub` so the host KAT can cross-check the baked max-thread field against every
// entry of the device-ID allowlist (`accel_intel_ids::vfe_max_threads_field`).
// One VFE value serves all accepted devices, which is only legal while they are
// all GT2; the test makes that coupling falsifiable instead of a comment.
pub const MEDIA_VFE_STATE_DW3: u32 = (167 << 16) | (2 << 8);
// MEDIA_VFE_STATE DW5 for the legacy one-thread kernels. URB Entry Allocation
// Size [31:16] is a U16-1 field; the historical raw value 2 allocates three
// 32-byte registers. CURBE Allocation Size [15:0] remains 0 because the payload
// is supplied through the GPGPU_WALKER indirect-data path, not MEDIA_CURBE_LOAD.
const MEDIA_VFE_STATE_DW5: u32 = 2 << 16;
const MEDIA_INTERFACE_DESCRIPTOR_LOAD_4DW: u32 = 0x7002_0002;
// One INTERFACE_DESCRIPTOR_DATA is 32 bytes (8 DWords), not 64.
const INTERFACE_DESCRIPTOR_TOTAL_LENGTH: u32 = 32;
const MEDIA_STATE_FLUSH_2DW: u32 = 0x7004_0000;
// GPGPU_WALKER on Gen9 is 15 DWords (length field 13 = 0x0d); the pre-iter6
// 0x7105_000b was the Gen7 13-DWord form. DW4 carries the SIMD-size field in
// bits [31:30]: 0b10 = SIMD32 (both kernels compile SIMD32 per their zeinfo).
const GPGPU_WALKER_15DW: u32 = 0x7105_000d;
const GPGPU_WALKER_SIMD32_THREADCOUNT: u32 = 0b10 << 30; // SIMD32, ThreadWidthMax=0 (1 thread)
// The no-op tolerates an all-lanes-live mask (it issues no memory access). The
// payload-carrying ops (Add, matmul) trim the Right/Bottom Execution Masks to their
// live-lane count via `lane_mask(work_items)` — otherwise the idle SIMD32 lanes
// would issue stray `a64 dword scattering write`s past the output buffer.
const GPGPU_WALKER_EXEC_MASK_FULL: u32 = 0xFFFF_FFFF;

// ---------------------------------------------------------------------------
// iter7/iter8 — stateless-A64 argument payload via the NEO indirect-data path.
//
// The finalizer Add reads its three buffer base pointers as raw A64 addresses
// from the GPGPU cross-thread payload. `add_f32x2.gen9.asm` reads them from
// r8.0/r8.1/r8.2 (qwords) and the per-lane `local_id.x` from r1/r2 — i.e. the
// thread payload is r0 header + 6 GRF per-thread local_id (r1..r6) + 3 GRF
// cross-thread (r7..r9), so a@byte32 -> r8.0, b@byte40 -> r8.1q, o@byte48 ->
// r8.2q. iter7 loaded only the cross-thread block (via MEDIA_CURBE_LOAD) and the
// 6-GRF per-thread block was never built, so cross-thread landed at the wrong GRF
// (Stage-B fault `fault_gpu_va=0xffb1ce9bb000`, garbage at r8). iter8 follows the
// NEO Gen9 convention (the toolchain that built the blob): one Indirect Object
// Heap = [cross-thread 96 B][per-thread local_id 192 B], delivered through the
// GPGPU_WALKER Indirect Data fields, and the IDD read-lengths split it into
// r7..r9 / r1..r6. See ADR-032 "Iteration 8 ISC-1" for the NEO field map.
//
// Cross-thread byte layout — the kernel ABI; oracle `add_f32x2.gen9.zeinfo`.
pub const CURBE_PAYLOAD_BYTES: usize = 96; // span [0,76) -> 3 GRF, padded to 96
pub const CURBE_CROSS_THREAD_GRF: u32 = 3; // IDD Cross-Thread Constant Data Read Length
pub const CURBE_OFF_GLOBAL_ID: usize = 0; // 3xu32 global_id_offset (0,0,0)
pub const CURBE_OFF_LOCAL_SIZE: usize = 12; // 3xu32 local_size
pub const CURBE_OFF_ARG_A: usize = 32; // A64 pointer of input a
pub const CURBE_OFF_ARG_B: usize = 40; // A64 pointer of input b
pub const CURBE_OFF_ARG_O: usize = 48; // A64 pointer of output o
pub const CURBE_OFF_ENQUEUED_LOCAL_SIZE: usize = 64; // 3xu32 enqueued_local_size

// Per-thread local_id block (`generateLocalIDsSimd`, NEO `local_id_gen.inl`):
// SIMD32 threadSkipSize = 32 * sizeof(u16) = 64 B; dimensionsOrder {0,1,2} puts
// local_id.x at byte 0 (r1/r2), .y at 64 (r3/r4), .z at 128 (r5/r6); 32 lanes x
// u16 per dim => 192 B = 6 GRF. The IDD Constant/Indirect URB Entry Read Length.
pub const LOCAL_ID_PAYLOAD_BYTES: usize = 192;
pub const CURBE_PER_THREAD_GRF: u32 = 6; // IDD Constant/Indirect URB Entry Read Length (192/32)
pub const LOCAL_ID_OFF_X: usize = 0; // local_id.x lanes 0..31 (u16), r1/r2
pub const LOCAL_ID_OFF_Y: usize = 64; // local_id.y, r3/r4
pub const LOCAL_ID_OFF_Z: usize = 128; // local_id.z, r5/r6

// The Indirect Object Heap the GPGPU_WALKER points at: [cross 96 B][per-thread 192 B].
pub const INDIRECT_HEAP_BYTES: usize = CURBE_PAYLOAD_BYTES + LOCAL_ID_PAYLOAD_BYTES; // 288
// GPGPU_WALKER Indirect Data Length = alignUp(cross + per-thread, 64) (NEO).
pub const WALKER_INDIRECT_DATA_LENGTH: u32 = (INDIRECT_HEAP_BYTES as u32).div_ceil(64) * 64; // 320

/// Build the 96-byte stateless-A64 cross-thread payload for the Add. `lhs`/`rhs`/
/// `output` are the buffers' absolute GPU virtual addresses (their GGTT bases in
/// the BUILD-4a legacy-ring layout). Layout per the kernel ABI above; pads zero.
pub fn build_curbe_payload(lhs: u64, rhs: u64, output: u64) -> [u8; CURBE_PAYLOAD_BYTES] {
    let mut p = [0u8; CURBE_PAYLOAD_BYTES];
    // local_size / enqueued_local_size = the Add NDRange (2,1,1).
    let local = [ADD_VECTOR_ELEMENTS as u32, 1, 1];
    write_u32x3(&mut p, CURBE_OFF_LOCAL_SIZE, local);
    p[CURBE_OFF_ARG_A..CURBE_OFF_ARG_A + 8].copy_from_slice(&lhs.to_le_bytes());
    p[CURBE_OFF_ARG_B..CURBE_OFF_ARG_B + 8].copy_from_slice(&rhs.to_le_bytes());
    p[CURBE_OFF_ARG_O..CURBE_OFF_ARG_O + 8].copy_from_slice(&output.to_le_bytes());
    write_u32x3(&mut p, CURBE_OFF_ENQUEUED_LOCAL_SIZE, local);
    p
}

/// Build the 192-byte per-thread `local_id` block for a single SIMD32 thread over
/// `active_lanes` work items: `local_id.x = [0, 1, …, active_lanes-1, 0, …]` across
/// the 32 lanes as `u16` (the idle lanes are masked off in the walker); `.y`/`.z` =
/// 0 (1-D NDRange). Channel layout per NEO `generateLocalIDsSimd` (x @ byte 0 =
/// r1/r2). `active_lanes` is clamped to the SIMD32 width.
pub fn build_local_id_payload_n(active_lanes: u32) -> [u8; LOCAL_ID_PAYLOAD_BYTES] {
    let mut p = [0u8; LOCAL_ID_PAYLOAD_BYTES];
    let lanes = if active_lanes > 32 { 32 } else { active_lanes };
    let mut lane = 0u32;
    while lane < lanes {
        let off = LOCAL_ID_OFF_X + (lane as usize) * 2;
        p[off..off + 2].copy_from_slice(&(lane as u16).to_le_bytes());
        lane += 1;
    }
    p
}

/// The Add's per-thread `local_id` (2-element NDRange): lane 0 = 0, lane 1 = 1.
pub fn build_local_id_payload() -> [u8; LOCAL_ID_PAYLOAD_BYTES] {
    build_local_id_payload_n(ADD_VECTOR_ELEMENTS as u32)
}

/// Slice-4's pinned 32x8 work-group is eight SIMD32 hardware threads. Each
/// thread consumes its own 192-byte local-id block; thread `t` has x lanes
/// 0..31 and y=t. This layout follows the pinned zeinfo and NEO's permissive
/// `generateLocalIDsSimd` shape (principle only, no code lift).
pub const BLUR_LOCAL_SIZE_X: u32 = 32;
pub const BLUR_LOCAL_SIZE_Y: u32 = 8;
pub const BLUR_THREADS_PER_GROUP: u32 = BLUR_LOCAL_SIZE_Y;
pub const BLUR_LOCAL_ID_PAYLOAD_BYTES: usize =
    LOCAL_ID_PAYLOAD_BYTES * BLUR_THREADS_PER_GROUP as usize;
pub const BLUR_INDIRECT_HEAP_BYTES: usize = CURBE_PAYLOAD_BYTES + BLUR_LOCAL_ID_PAYLOAD_BYTES;
pub const BLUR_WALKER_INDIRECT_DATA_LENGTH: u32 =
    (BLUR_INDIRECT_HEAP_BYTES as u32).div_ceil(64) * 64;
// KBL PRM Vol. 2a, MEDIA_VFE_STATE DW5: when GPGPU_WALKER uses indirect data,
// the URB entry allocation must be large enough for the entire indirect-data
// payload. The field is U16-1 in 32-byte register units, so Slice 4's
// 1,664-byte payload needs 52 registers and encodes 51. Keeping the legacy
// three-register value here truncates the eight-thread local-ID payload.
pub const BLUR_URB_ENTRY_ALLOCATION_REGS: u32 = BLUR_WALKER_INDIRECT_DATA_LENGTH.div_ceil(32);
const BLUR_MEDIA_VFE_STATE_DW5: u32 = (BLUR_URB_ENTRY_ALLOCATION_REGS - 1) << 16;

pub fn build_blur_local_id_payload() -> [u8; BLUR_LOCAL_ID_PAYLOAD_BYTES] {
    let mut payload = [0u8; BLUR_LOCAL_ID_PAYLOAD_BYTES];
    let mut thread = 0u32;
    while thread < BLUR_THREADS_PER_GROUP {
        let base = thread as usize * LOCAL_ID_PAYLOAD_BYTES;
        let mut lane = 0u32;
        while lane < BLUR_LOCAL_SIZE_X {
            let x = base + LOCAL_ID_OFF_X + lane as usize * 2;
            payload[x..x + 2].copy_from_slice(&(lane as u16).to_le_bytes());
            let y = base + LOCAL_ID_OFF_Y + lane as usize * 2;
            payload[y..y + 2].copy_from_slice(&(thread as u16).to_le_bytes());
            lane += 1;
        }
        thread += 1;
    }
    payload
}

// BUILD-4b-1 matmul cross-thread arg ABI (read from `matmul_f32.gen9.zeinfo` — its
// own contract, NOT the Add's): a@32, b@40, c@48 (A64 ptrs, same offsets as the
// Add's a/b/o); m@56, n@60, k@64 (byvalue i32 dims); enqueued_local_size@68. Span
// [0,80) -> 3 GRF cross-thread, 6 GRF per-thread local_id, SIMD32 — the same 4a
// indirect-data substrate as the Add; only the dims + enqueued offset differ.
pub const MATMUL_OFF_ARG_A: usize = 32;
pub const MATMUL_OFF_ARG_B: usize = 40;
pub const MATMUL_OFF_ARG_C: usize = 48;
pub const MATMUL_OFF_M: usize = 56;
pub const MATMUL_OFF_N: usize = 60;
pub const MATMUL_OFF_K: usize = 64;
pub const MATMUL_OFF_ENQUEUED_LOCAL_SIZE: usize = 68;

/// Matmul GPU output tolerance vs **host f32** (Phase-5 precedent for accumulating
/// ops; ADR-032 BUILD-4b-1): ≤ 2⁻¹² relative error. The Add (non-accumulating) stays
/// byte-exact (0 ULP). Hardware f32 tracks host f32 more closely than soft-float, so
/// the reference is host f32, not the accel_cpu soft-float backend.
pub const MATMUL_REL_TOLERANCE: f32 = 1.0 / 4096.0; // 2⁻¹²

/// True if every f32 element of `gpu` is within [`MATMUL_REL_TOLERANCE`] of the
/// corresponding host-f32 element of `host`: `|g - h| ≤ tol · max(|h|, 1.0)` (a
/// relative bound that also covers near-zero references). Both are LE f32 bytes.
pub fn matmul_within_tolerance(gpu: &[u8], host: &[u8]) -> bool {
    if gpu.len() != host.len() || !gpu.len().is_multiple_of(4) {
        return false;
    }
    let mut i = 0;
    while i + 4 <= gpu.len() {
        let g = f32::from_le_bytes([gpu[i], gpu[i + 1], gpu[i + 2], gpu[i + 3]]);
        let h = f32::from_le_bytes([host[i], host[i + 1], host[i + 2], host[i + 3]]);
        let scale = if h.abs() > 1.0 { h.abs() } else { 1.0 };
        let diff = if g > h { g - h } else { h - g };
        // NaN (incomparable) or over-tolerance fails; both are non-negated f32 tests.
        if diff.is_nan() || diff > MATMUL_REL_TOLERANCE * scale {
            return false;
        }
        i += 4;
    }
    true
}

/// Max relative error `|g − h| / max(|h|, 1.0)` across all f32 elements, scaled to
/// fixed-point units of 2⁻²⁴ (so the 2⁻¹² tolerance = 4096 units) for Stage-B serial
/// logging without no_std float formatting. Returns `u32::MAX` on a NaN/length
/// mismatch. The tolerance threshold in these units is `MATMUL_REL_TOLERANCE_E24`.
pub const MATMUL_REL_TOLERANCE_E24: u32 = 4096; // 2⁻¹² · 2²⁴
pub fn matmul_max_rel_error_e24(gpu: &[u8], host: &[u8]) -> u32 {
    if gpu.len() != host.len() || !gpu.len().is_multiple_of(4) {
        return u32::MAX;
    }
    let mut max = 0u32;
    let mut i = 0;
    while i + 4 <= gpu.len() {
        let g = f32::from_le_bytes([gpu[i], gpu[i + 1], gpu[i + 2], gpu[i + 3]]);
        let h = f32::from_le_bytes([host[i], host[i + 1], host[i + 2], host[i + 3]]);
        let scale = if h.abs() > 1.0 { h.abs() } else { 1.0 };
        let diff = if g > h { g - h } else { h - g };
        let rel = diff / scale;
        if rel.is_nan() {
            return u32::MAX;
        }
        let scaled = rel * 16_777_216.0; // · 2²⁴
        let e24 = if scaled >= u32::MAX as f32 {
            u32::MAX
        } else {
            scaled as u32
        };
        if e24 > max {
            max = e24;
        }
        i += 4;
    }
    max
}

/// Build the 96-byte stateless-A64 cross-thread payload for the matmul. `a`/`b`/`c`
/// are the operands' absolute GPU virtual addresses (GGTT bases); `m`/`n`/`k` are
/// the row-major dims (A is m×k, B is k×n, C is m×n). The NDRange is 1-D over m·n
/// output elements (local_size = m·n). Layout per `matmul_f32.gen9.zeinfo`.
pub fn build_matmul_curbe_payload(
    a: u64,
    b: u64,
    c: u64,
    m: u32,
    n: u32,
    k: u32,
) -> [u8; CURBE_PAYLOAD_BYTES] {
    let mut p = [0u8; CURBE_PAYLOAD_BYTES];
    let local = [m.saturating_mul(n), 1, 1];
    write_u32x3(&mut p, CURBE_OFF_LOCAL_SIZE, local); // @12
    p[MATMUL_OFF_ARG_A..MATMUL_OFF_ARG_A + 8].copy_from_slice(&a.to_le_bytes());
    p[MATMUL_OFF_ARG_B..MATMUL_OFF_ARG_B + 8].copy_from_slice(&b.to_le_bytes());
    p[MATMUL_OFF_ARG_C..MATMUL_OFF_ARG_C + 8].copy_from_slice(&c.to_le_bytes());
    p[MATMUL_OFF_M..MATMUL_OFF_M + 4].copy_from_slice(&m.to_le_bytes());
    p[MATMUL_OFF_N..MATMUL_OFF_N + 4].copy_from_slice(&n.to_le_bytes());
    p[MATMUL_OFF_K..MATMUL_OFF_K + 4].copy_from_slice(&k.to_le_bytes());
    write_u32x3(&mut p, MATMUL_OFF_ENQUEUED_LOCAL_SIZE, local); // @68
    p
}

// BUILD-4b-2 GELU cross-thread arg ABI (read from `gelu_f32.gen9.zeinfo` — its OWN
// contract, extracted not assumed). Pointwise (in, out, count): in@32, out@40 (A64
// ptrs, same offsets as the Add's a/o and matmul's a/b); count@48 (byvalue i32);
// enqueued_local_size@52. The payload span ends at byte 64, so the cross-thread
// block is exactly 2 GRF (NEO `setGrfInfo`: ceil(64/32)=2) — one fewer than the
// Add/matmul's 3 GRF (their span runs to 76/80). The per-thread local_id block (6
// GRF, SIMD32) and the indirect-data substrate are otherwise identical. Honoring
// the 2-GRF cross-thread read length is what NEO itself programs for this kernel.
pub const GELU_OFF_ARG_IN: usize = 32;
pub const GELU_OFF_ARG_OUT: usize = 40;
pub const GELU_OFF_COUNT: usize = 48;
pub const GELU_OFF_ENQUEUED_LOCAL_SIZE: usize = 52;
/// IDD Cross-Thread Constant Data Read Length for GELU: 2 GRF (span [0,64)), vs the
/// Add/matmul's 3. The kernel reads in/out/count from r8 (the 2nd cross-thread GRF),
/// which a 2-GRF read length loads; the 3rd GRF (the Add/matmul's m/n/k region) is
/// unused by the pointwise kernel and not read.
pub const GELU_CROSS_THREAD_GRF: u32 = 2;

/// Build the 96-byte stateless-A64 cross-thread payload for GELU. `in_ptr`/`out_ptr`
/// are the operands' absolute GPU virtual addresses (GGTT bases); `count` is the
/// element count (1-D NDRange over `count`, local_size = count). Layout per
/// `gelu_f32.gen9.zeinfo`: in@32, out@40, count@48 (i32), enqueued_local_size@52.
pub fn build_gelu_curbe_payload(
    in_ptr: u64,
    out_ptr: u64,
    count: u32,
) -> [u8; CURBE_PAYLOAD_BYTES] {
    let mut p = [0u8; CURBE_PAYLOAD_BYTES];
    let local = [count, 1, 1];
    write_u32x3(&mut p, CURBE_OFF_LOCAL_SIZE, local); // @12
    p[GELU_OFF_ARG_IN..GELU_OFF_ARG_IN + 8].copy_from_slice(&in_ptr.to_le_bytes());
    p[GELU_OFF_ARG_OUT..GELU_OFF_ARG_OUT + 8].copy_from_slice(&out_ptr.to_le_bytes());
    p[GELU_OFF_COUNT..GELU_OFF_COUNT + 4].copy_from_slice(&count.to_le_bytes());
    write_u32x3(&mut p, GELU_OFF_ENQUEUED_LOCAL_SIZE, local); // @52
    p
}

/// GELU GPU output tolerance vs **host f32** (libm reference): ≤ 2⁻¹² relative — the
/// same Phase-5 bound as matmul. Unlike matmul (bit-exact because Gen9 has no FMA),
/// GELU's hardware extended-math `tanh` (math.exp/inv/fdiv) genuinely diverges from
/// host libm and from the soft-float `accel_cpu` path, so this bound fires
/// non-vacuously. The relative check itself is op-agnostic (delegates to the matmul
/// checker); the GELU-named wrappers document the call-site and reference.
pub const GELU_REL_TOLERANCE: f32 = MATMUL_REL_TOLERANCE;
pub const GELU_REL_TOLERANCE_E24: u32 = MATMUL_REL_TOLERANCE_E24;
pub fn gelu_within_tolerance(gpu: &[u8], host: &[u8]) -> bool {
    matmul_within_tolerance(gpu, host)
}
pub fn gelu_max_rel_error_e24(gpu: &[u8], host: &[u8]) -> u32 {
    matmul_max_rel_error_e24(gpu, host)
}

fn write_u32x3(dst: &mut [u8], offset: usize, values: [u32; 3]) {
    for (i, v) in values.iter().enumerate() {
        let base = offset + i * 4;
        dst[base..base + 4].copy_from_slice(&v.to_le_bytes());
    }
}

/// SIMD32 right/bottom execution mask for `work_items` live lanes (1-D NDRange,
/// one thread group of ≤32 work items). 32 lanes → all-ones; fewer → low bits set.
pub const fn lane_mask(work_items: u32) -> u32 {
    if work_items >= 32 {
        0xFFFF_FFFF
    } else {
        (1u32 << work_items) - 1
    }
}

// ---------------------------------------------------------------------------
// Iteration 6 — STATE_BASE_ADDRESS (the iter5 SUSPECT-A fix).
//
// iter5 proved the dispatch sets up a thread on EU row-0 but its *instruction
// fetch* stalls (INSTDONE bit 16 busy / bit 21 stuck), with SC/SAMPLER idle and
// RING_FAULT=0 — the EU cannot fetch the kernel's instructions. On Gen9 the EU
// fetches code from Instruction Base Address + the descriptor's kernel-start
// pointer, and the interface descriptor itself is read from Dynamic State Base
// Address. The pre-iter6 batch never issued STATE_BASE_ADDRESS, so those bases
// were unset and the kernel pointer resolved to nowhere — exactly this signature.
//
// We program every base = 0 so the descriptor's kernel-start pointer (0x120000)
// and the IDL descriptor offset (0x110000) are absolute GGTT offsets (the driver
// already GGTT-maps those pages), with the four buffer-size bounds = max so the
// region at GGTT 0x110000..0x133000 is in range. General State Base = 0 is also
// what iter7's stateless-A64 Add needs (its cross-thread pointers are absolute
// GPU addresses); no Surface State heap is required because the Add is stateless.
//
// Gen9 STATE_BASE_ADDRESS is 19 DWords (KBL PRM Vol. 2a). Header opcode:
//   type[31:29]=011 GFXPIPE, subtype[28:27]=00 common, opcode[26:24]=001,
//   subopcode[23:16]=0x01, length[7:0]=19-2=0x11  ->  0x6101_0011.
// Each base-address low DWord carries the address in [31:12], a MOCS index in
// [10:4] (0 = uncached, safe for bring-up), and a Modify-Enable in bit 0. Each
// buffer-size DWord carries the size in pages in [31:12] and a Modify-Enable in
// bit 0; 0xFFFFF in [31:12] = the maximum bound.
const STATE_BASE_ADDRESS_19DW: u32 = 0x6101_0011;
const SBA_BASE_MODIFY_ENABLE: u32 = 1; // bit 0 of a base-address low DWord
const SBA_SIZE_MAX_ENABLE: u32 = 0xFFFF_F000 | 1; // size [31:12]=max | enable[0]

pub const STATE_BASE_ADDRESS_DWORDS: usize = 19;

