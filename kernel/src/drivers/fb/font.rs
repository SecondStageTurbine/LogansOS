/// Look up the bitmap for a character. Returns the fallback glyph for
/// anything not in the table.
pub fn glyph(c: char) -> &'static Glyph {
    for (ch, g) in GLYPHS {
        if *ch == c {
            return g;
        }
    }
    #[cfg(any(
        all(
            feature = "fb-progress-console",
            any(feature = "xhci-silicon", feature = "i2c-hid-touchpad")
        ),
        feature = "freeze-watchdog"
    ))]
    for (ch, g) in EXTRA_GLYPHS {
        if *ch == c {
            return g;
        }
    }
    &FALLBACK
}
