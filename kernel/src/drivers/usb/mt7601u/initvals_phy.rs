//! MT7601U RF + BBP-mode init tables (Phase 7.5 BUILD-W1) — transcribed
//! byte-faithfully from the Linux `mt7601u` driver `initvals_phy.h` (v6.6,
//! GPL-2.0).
//!
//! RF reg pairs encode their full MCU address as `MT_MCU_MEMMAP_RF |
//! (bank << 16) | reg` (the upstream `RF_REG_PAIR` macro) and are written via
//! `mcu_write_reg_pairs(base = 0, ...)`. The BBP-mode tables are `(BBP reg #,
//! val)` written to `MT_MCU_MEMMAP_BBP`. The per-channel frequency plan is the
//! static table inside `__mt7601u_phy_set_channel` (RF bank-0 regs 17..20).

#![allow(dead_code)]

use super::regs::MCU_MEMMAP_RF;

/// `RF_REG_PAIR(bank, reg)` → the full RF MCU address.
const fn rf(bank: u32, reg: u32) -> u32 {
    MCU_MEMMAP_RF | (bank << 16) | reg
}

