"""Kerning oracle from an independent shaper: HarfBuzz (system libharfbuzz,
via ctypes) shapes every printable-ASCII pair at scale = unitsPerEm, and the
pair's kerning is the first glyph's shaped x_advance minus its hmtx advance.

HarfBuzz implements the full OpenType GPOS lookup semantics (subtable
fall-through, extension lookups, class definitions) with no code shared with
neo-text or with this repo's fontTools-based oracles. neo-text applies no GSUB,
so HarfBuzz's default-on substitution features (ccmp, locl, rlig, rclt, calt,
clig, liga) are turned off: otherwise Inter's contextual alternates (e.g. the
case-sensitive punctuation before capitals) replace the cmap glyphs and the pair
measures a different glyph. Pairs HarfBuzz still does not shape to the two cmap
glyphs are skipped and listed.

Usage: harfbuzz_kern_oracle.py <font.ttf>   (Rust fixture on stdout)
"""
import ctypes as C
import struct
import sys

hb = C.CDLL("libharfbuzz.so.0")
for fn, rt in [("hb_blob_create_from_file", C.c_void_p), ("hb_face_create", C.c_void_p),
               ("hb_font_create", C.c_void_p), ("hb_buffer_create", C.c_void_p),
               ("hb_buffer_get_glyph_positions", C.c_void_p),
               ("hb_buffer_get_glyph_infos", C.c_void_p)]:
    getattr(hb, fn).restype = rt
hb.hb_blob_create_from_file.argtypes = [C.c_char_p]
hb.hb_face_create.argtypes = [C.c_void_p, C.c_uint]
hb.hb_font_create.argtypes = [C.c_void_p]
hb.hb_font_set_scale.argtypes = [C.c_void_p, C.c_int, C.c_int]
hb.hb_font_get_nominal_glyph.argtypes = [C.c_void_p, C.c_uint32, C.POINTER(C.c_uint32)]
hb.hb_font_get_glyph_h_advance.argtypes = [C.c_void_p, C.c_uint32]
hb.hb_font_get_glyph_h_advance.restype = C.c_int32
hb.hb_face_get_upem.argtypes = [C.c_void_p]
hb.hb_buffer_add_utf8.argtypes = [C.c_void_p, C.c_char_p, C.c_int, C.c_uint, C.c_int]
hb.hb_buffer_guess_segment_properties.argtypes = [C.c_void_p]
hb.hb_shape.argtypes = [C.c_void_p, C.c_void_p, C.c_void_p, C.c_uint]
hb.hb_buffer_get_glyph_positions.argtypes = [C.c_void_p, C.POINTER(C.c_uint)]
hb.hb_buffer_get_glyph_infos.argtypes = [C.c_void_p, C.POINTER(C.c_uint)]
hb.hb_buffer_destroy.argtypes = [C.c_void_p]


class Feature(C.Structure):
    _fields_ = [("tag", C.c_uint32), ("value", C.c_uint32), ("start", C.c_uint), ("end", C.c_uint)]


hb.hb_feature_from_string.argtypes = [C.c_char_p, C.c_int, C.POINTER(Feature)]
NO_GSUB = [b"-ccmp", b"-locl", b"-rlig", b"-rclt", b"-calt", b"-clig", b"-liga"]


def features():
    out = (Feature * len(NO_GSUB))()
    for i, text in enumerate(NO_GSUB):
        if not hb.hb_feature_from_string(text, len(text), C.byref(out[i])):
            raise SystemExit("bad feature %r" % text)
    return out


class Pos(C.Structure):
    _fields_ = [("xa", C.c_int32), ("ya", C.c_int32), ("xo", C.c_int32), ("yo", C.c_int32), ("v", C.c_uint32)]


class Info(C.Structure):
    _fields_ = [("cp", C.c_uint32), ("mask", C.c_uint32), ("cl", C.c_uint32), ("v1", C.c_uint32), ("v2", C.c_uint32)]


def main(path):
    face = hb.hb_face_create(hb.hb_blob_create_from_file(path.encode()), 0)
    upem = hb.hb_face_get_upem(face)
    font = hb.hb_font_create(face)
    hb.hb_font_set_scale(font, upem, upem)

    def gid(ch):
        g = C.c_uint32()
        return g.value if hb.hb_font_get_nominal_glyph(font, ord(ch), C.byref(g)) else 0

    feats = features()
    chars = [chr(c) for c in range(0x20, 0x7F)]
    pairs, skipped = [], []
    for a in chars:
        for b in chars:
            buf = hb.hb_buffer_create()
            s = (a + b).encode()
            hb.hb_buffer_add_utf8(buf, s, len(s), 0, len(s))
            hb.hb_buffer_guess_segment_properties(buf)
            hb.hb_shape(font, buf, feats, len(NO_GSUB))
            n = C.c_uint()
            pos = C.cast(hb.hb_buffer_get_glyph_positions(buf, C.byref(n)), C.POINTER(Pos))
            info = C.cast(hb.hb_buffer_get_glyph_infos(buf, C.byref(n)), C.POINTER(Info))
            if n.value != 2 or info[0].cp != gid(a) or info[1].cp != gid(b):
                skipped.append(a + b)
            else:
                k = pos[0].xa - hb.hb_font_get_glyph_h_advance(font, gid(a))
                if k:
                    pairs.append((a, b, k))
            hb.hb_buffer_destroy(buf)
    print("// Generated by scripts/fonts/harfbuzz_kern_oracle.py %s" % path)
    print("// HarfBuzz-shaped kerning (font units) for every printable-ASCII pair;")
    print("// pairs not listed kern by 0. %d nonzero, %d skipped (not shaped to 2 cmap glyphs)."
          % (len(pairs), len(skipped)))
    print("pub const SKIPPED: &[&str] = &[%s];" % ", ".join('"%s"' % p.replace("\\", "\\\\").replace('"', '\\"') for p in skipped))
    print("#[rustfmt::skip]\npub const PAIRS: &[(char, char, i32)] = &[")
    esc = lambda c: {"'": "\\'", "\\": "\\\\"}.get(c, c)
    line = []
    for a, b, k in pairs:
        line.append("('%s', '%s', %d)" % (esc(a), esc(b), k))
        if len(line) == 6:
            print("    " + ", ".join(line) + ",")
            line = []
    if line:
        print("    " + ", ".join(line) + ",")
    print("];")


if __name__ == "__main__":
    main(sys.argv[1])
