"""Independent oracle for the desktop-clock Home readout (OT-85).

Written from the spec text in userland/neo-atrium/src/layout.rs
(`Layout::clock_box`: the field's x and width, 84 px tall, ending 28 px above
the field's focus light, never above the craft bar), typed here again rather
than read from the Rust: the host test compares the two boxes.

The readout's words change every minute, so the kernel does not hold them to
a digest. It holds the rest of the screen: the desktop-intro session's final
Home (the hint shown, the field focused and empty) rendered by
scripts/desktop/scene_oracle.py, which draws no clock at all, digested with
the Home label boxes, the hint box AND the readout box masked. A capture whose
clock drew a single pixel outside its box fails it.

usage: clock_oracle.py fixture > fixtures/desktop-clock/clock.rs
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "fonts"))
sys.path.insert(0, HERE)

import area_oracle as ao  # noqa: E402
import field_oracle as fo  # noqa: E402
import label_oracle as lo  # noqa: E402
import scene_oracle as so  # noqa: E402

CLOCK_GAP, CLOCK_H = 28, 84


def clock_box(L):
    fx, fy, fw, _fh = L["field"]
    top = max(fy - so.GLOW - CLOCK_GAP - CLOCK_H, so.BAR_H)
    return (fx, top, fw, CLOCK_H)


def fixture():
    print("// SPDX-License-Identifier: MPL-2.0")
    print("// GENERATED by scripts/desktop/clock_oracle.py fixture — do not edit.")
    print("// desktop-clock (OT-85): the Home readout's box, and the desktop-intro")
    print("// final Home (hint shown) with that box masked as well as the three Home")
    print("// label boxes and the hint box: FNV-1a over every other pixel. Rendered by")
    print("// scene_oracle.py, which draws no clock. Independent of neo-atrium.")
    for (W, H) in ((1920, 1080), (1280, 800)):
        L = so.layout(W, H)
        print("pub const CLOCK_BOX_%dX%d: (usize, usize, usize, usize) = (%d, %d, %d, %d);"
              % ((W, H) + clock_box(L)))
    W, H = 1920, 1080
    L = so.layout(W, H)
    # The session's two captures (host-checked): the intro card at start,
    # eight rows with the clock (the greeting-and-time row, then the name),
    # and the help card (six rows) at the end; text boxes and readout masked.
    for name, n in (("INTRO", 8), ("HELP", 6)):
        print("pub const %s_CLOCK_TEXT_BOX: (usize, usize, usize, usize) = (%d, %d, %d, %d);"
              % ((name,) + so.card_text(L, n)))
        rgb, Lr = so.render(W, H, "glass", True, "home", card_rows=n)
        masks = Lr["home_labels"] + [so.card_text(L, n), clock_box(L)]
        d = so.digest(rgb, dict(Lr, labels=masks))
        print("pub const %s_CLOCK_GLASS_1920X1080: u64 = 0x%016x;" % (name, d))
    for mode in ("glass", "rt"):
        rgb, Lr = so.render(W, H, mode, True, "home", card_rows=0)
        masks = Lr["home_labels"] + [so.card_text(L, 1), clock_box(L)]
        d = so.digest(rgb, dict(Lr, labels=masks))
        print("pub const HINT_CLOCK_%s_1920X1080: u64 = 0x%016x;" % (mode.upper(), d))
    # The DS-1a field check on that Home (intro_oracle's HINT_FIELD_*), the
    # readout box masked too.
    face = ao.Face(lo.FONT)
    home = L["home_labels"]
    layers, _fg, _px, caret = fo.run(face, L, "", True)
    win = fo.window(layers, caret, fo.text_box(L))
    rgb, Lr = so.render(W, H, "glass", True, "home")
    d = so.digest(rgb, dict(Lr, labels=[home[0], home[2], win, so.card_text(L, 1), clock_box(L)]))
    print("/// The field's empty-focused window (field_oracle) and the Glass Home")
    print("/// digest with only it, the bar and chip label boxes, the hint box and the")
    print("/// readout box masked.")
    print("pub const FIELD_WINDOW: (usize, usize, usize, usize) = (%d, %d, %d, %d);" % win)
    print("pub const HINT_FIELD_CLOCK_GLASS_1920X1080: u64 = 0x%016x;" % d)


def main():
    if len(sys.argv) == 2 and sys.argv[1] == "fixture":
        fixture()
        return
    print(__doc__)
    sys.exit(2)


if __name__ == "__main__":
    main()
