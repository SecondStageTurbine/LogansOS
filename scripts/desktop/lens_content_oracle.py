"""Byte oracle for the DS-1c Lens's content (what the instrument draws).

The Lens (neo-worker `desktop-lens`) lists the directory it is lent and draws
the names; the scene oracle masks its client area. This oracle pins every
pixel of that client instead, independently of neo-text and neo-worker:

* the listing is the test boot's temporary root, in its readdir order, as
  kernel/src/fs/mod.rs seeds it (hello.txt, scratch, dir, link — `dir` a
  directory, shown with a trailing `/`);
* the drawing rule is the THINK's DS-1c Lens text: the content floor; the
  path "/" at 12 px in the secondary label colour at x = 16, baseline 26;
  then one name per line at 14 px in the primary colour, x = 16, baselines
  54 + 22 i (at most 15; a 12 px secondary footer "and more…" or "(empty)"
  on the next line when needed);
* glyph coverage by exact area (scripts/fonts/area_oracle via label_oracle:
  fontTools outlines, f64 clipping, neo-text's *specified* stem darkening and
  1/4-px origins), with per-pixel [lo, hi] bounds (+/- slack, linear light)
  over a tight window around each line's ink.

Every client pixel outside those windows must be the floor exactly, so a
missing, extra, reordered or misspelt name fails, and so does any ink
outside its line.

usage: lens_content_oracle.py fixture > fixtures/desktop-ds1/lens_content.rs
       lens_content_oracle.py labels  > fixtures/desktop-ds1/lens_labels.rs
       lens_content_oracle.py dock-labels > fixtures/desktop-dl1/dock_labels.rs

`labels`: the Lens's own chrome text, exact (AAG): the title "Lens" and its
read-only cue "· read-only" (the security-relevant label, spec v1.4: as
Arthur's title and "· owned"), and the second chip's "L" / "Lens" (as the first
chip's). The same exact-area windows and [lo, hi] bounds as label_oracle,
over the scene oracle's own background — for the Arthur-focused capture and
for the Lens-selected one.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "fonts"))
sys.path.insert(0, HERE)

import area_oracle as ao  # noqa: E402
import label_oracle as lo  # noqa: E402
import scene_oracle as so  # noqa: E402

FLOOR = 0x0A0E27
PRIMARY = 0xFFFFFF
SECONDARY = 0xC8CDD2
INSET = 16.0
LINE = 22
MAX_ENTRIES = 15
# (name, is_directory) in readdir order: the test boot's temporary root.
ROOT_LISTING = [("hello.txt", False), ("scratch", False), ("dir", True), ("link", False)]


def lines():
    """(name, text, px, x, baseline, colour) per drawn line, Lens-local."""
    out = [("PATH", "/", 12.0, INSET, 26, SECONDARY)]
    shown = ROOT_LISTING[:MAX_ENTRIES]
    for i, (name, is_dir) in enumerate(shown):
        out.append(("ENTRY%d" % i, name + ("/" if is_dir else ""), 14.0, INSET, 54 + i * LINE,
                    PRIMARY))
    footer = "and more…" if len(ROOT_LISTING) > MAX_ENTRIES else (
        "(empty)" if not shown else None)
    if footer:
        out.append(("FOOTER", footer, 12.0, INSET, 54 + len(shown) * LINE, SECONDARY))
    return out


def fixture():
    face = ao.Face(lo.FONT)
    lens = so.layout(1920, 1080)["lens"]
    cx, cy, cw, ch = lens["client"]
    clip = (0, 0, cw, ch)
    spec = lines()
    print("// SPDX-License-Identifier: MPL-2.0")
    print("// GENERATED by scripts/desktop/lens_content_oracle.py fixture — do not edit.")
    print("// DS-1c: the Lens's client, exact: per-line glyph windows with per-pixel")
    print("// [lo, hi] bounds (exact-area coverage +/-%d/255 over the content floor)," % lo.SLACK)
    print("// every other client pixel the floor. Independent of neo-text and neo-worker.")
    print("/// The Lens client (x, y, w, h) at 1920x1080.")
    print("pub const LENS_CLIENT: (usize, usize, usize, usize) = (%d, %d, %d, %d);" % (cx, cy, cw, ch))
    print("pub const FLOOR: u32 = 0x%06x;" % FLOOR)
    print("/// The lines drawn: %s." % ", ".join(repr(s[1]) for s in spec))
    windows = []
    tables = []
    for name, text, px, x0, base, fg in spec:
        layers = lo.run_coverage(face, text, px, x0, base, clip)
        win = lo.window_of(layers, clip)
        lo_t, hi_t = lo.bounds(layers, px, fg, win, lambda x, y: FLOOR)
        windows.append(win)
        tables.append((name, lo_t, hi_t, win[2]))
    print("/// Line windows (x, y, w, h), Lens-client-local, in drawing order.")
    print("pub const WINDOWS: [(usize, usize, usize, usize); %d] = [" % len(windows))
    for (name, *_r), win in zip(spec, windows):
        print("    (%d, %d, %d, %d), // %s" % (win + (name,)))
    print("];")
    for name, lo_t, hi_t, ww in tables:
        for half, table in (("LO", lo_t), ("HI", hi_t)):
            print("#[rustfmt::skip]")
            print("pub const %s_%s: [u32; %d] = [" % (name, half, len(table)))
            for i in range(0, len(table), ww):
                print("    " + ", ".join("0x%06x" % v for v in table[i:i + ww]) + ",")
            print("];")
    print("/// (LO, HI) per line, in WINDOWS order.")
    print("pub const BOUNDS: [(&[u32], &[u32]); %d] = [" % len(tables))
    for name, *_r in tables:
        print("    (&%s_LO, &%s_HI)," % (name, name))
    print("];")


def label_runs(face, L):
    """(name, text, px, x, baseline, colour, clip box), spec v1.4."""
    lens = L["lens"]
    tx, ty = lens["title"][0], lens["title"][1]
    x = float(tx + 4)
    cx = L["chip2"][0] + L["chip2"][2] / 2.0
    cy = L["chip2"][1]
    return [
        ("TITLE", "Lens", 14.0, x, ty + 18, lo.PRIMARY, lens["title"]),
        ("TITLE_TRUST", "\u00b7 read-only", 11.0, x + lo.measure(face, 14.0, "Lens") + 8.0,
         ty + 18, lo.SECONDARY, lens["title"]),
        ("CHIP2_MONO", "L", 20.0, cx - lo.measure(face, 20.0, "L") / 2.0, cy + 30, lo.PRIMARY,
         L["chip2_label"]),
        ("CHIP2_NAME", "Lens", 10.0, cx - lo.measure(face, 10.0, "Lens") / 2.0, cy + 47,
         lo.SECONDARY, L["chip2_label"]),
    ]


def labels(frame_at=None, client=(640, 400), states=(("FOCUSED", True, False),
                                                       ("SELECTED", False, True)),
           header="DS-1c: the Lens title with its read-only cue and the second chip's text,"):
    """frame_at / client (DL-1): the window moved / resized with the Lens
    docked; the Lens title's glass (and so its bounds) is the docked place's."""
    face = ao.Face(lo.FONT)
    L = so.layout(1920, 1080, client[0], client[1], frame_at=frame_at)
    spec = label_runs(face, L)
    layers = {n: lo.run_coverage(face, t, px, x0, b, clip) for n, t, px, x0, b, _f, clip in spec}
    windows = {n: lo.window_of(layers[n], clip) for n, *_r, clip in spec}
    names = [r[0] for r in spec]
    print("// SPDX-License-Identifier: MPL-2.0")
    print("// GENERATED by scripts/desktop/lens_content_oracle.py %s — do not edit."
          % ("labels" if frame_at is None else "dock-labels"))
    print("// " + header)
    print("// exact: per-run glyph windows with per-pixel [lo, hi] bounds (exact-area")
    print("// coverage +/-%d/255 over the scene oracle's background), for the" % lo.SLACK)
    print("// Arthur-focused and the Lens-selected captures. Independent of neo-text and")
    print("// neo-atrium.")
    print("/// Label runs: %s." % ", ".join("%s = %r" % (r[0], r[1]) for r in spec))
    print("pub const RUNS: [&str; %d] = [%s];" % (len(names), ", ".join('"%s"' % n for n in names)))
    print("/// Glyph windows (x, y, w, h) at 1920x1080, in RUNS order.")
    print("pub const WINDOWS: [(usize, usize, usize, usize); %d] = [" % len(names))
    for n in names:
        print("    (%d, %d, %d, %d), // %s" % (windows[n] + (n,)))
    print("];")
    for tag, focused, sel in states:
        rgb, _ = so.render(1920, 1080, "glass", focused, "window", lens=True, lens_sel=sel,
                           frame_at=frame_at, client=client)

        def bg_at(x, y, rgb=rgb):
            p = rgb[y, x]
            return (int(p[0]) << 16) | (int(p[1]) << 8) | int(p[2])

        for name, _t, px, _x0, _b, fg, _c in spec:
            lo_t, hi_t = lo.bounds(layers[name], px, fg, windows[name], bg_at)
            ww = windows[name][2]
            for half, table in (("LO", lo_t), ("HI", hi_t)):
                print("#[rustfmt::skip]")
                print("pub static %s_%s_%s: [u32; %d] = [" % (tag, name, half, len(table)))
                for i in range(0, len(table), ww):
                    print("    " + ", ".join("0x%06x" % v for v in table[i:i + ww]) + ",")
                print("];")
        print("pub static %s_BOUNDS: [(&[u32], &[u32]); %d] = [" % (tag, len(names)))
        for n in names:
            print("    (&%s_%s_LO, &%s_%s_HI)," % (tag, n, tag, n))
        print("];")


def main():
    if len(sys.argv) == 2 and sys.argv[1] == "fixture":
        fixture()
        return
    if len(sys.argv) == 2 and sys.argv[1] == "labels":
        labels()
        return
    if len(sys.argv) == 2 and sys.argv[1] == "dock-labels":
        # DL-1: desktop_full_boot's capture (scene_oracle.py DOCK_CASES[0]).
        fx, fy, cw, ch = so.DOCK_CASES[0]
        labels(frame_at=(fx, fy), client=(cw, ch), states=(("FOCUSED", True, False),),
               header="DL-1: the docked Lens's title and the second chip's text,")
        return
    print(__doc__)
    sys.exit(2)


if __name__ == "__main__":
    main()
