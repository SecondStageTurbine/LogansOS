"""Exact oracle for the DS-1 Home intent field (Codex DS-1a F2).

The Home scene oracle hashes the field's whole text box as zero, so deleting
the placeholder, the typed intent or the caret — DS-1a's primary interaction
— left every independent check green. This oracle covers them, independently
of neo-text and neo-atrium, from the scene spec's field rules (neo-atrium
lib.rs, "Home view", v1.3.1):

* the run (placeholder 16 px secondary, or the typed text 18 px primary,
  scrolled left by `room = T.w - 4`) by exact-area glyph coverage
  (scripts/fonts/area_oracle via label_oracle: fontTools outlines, f64
  clipping, neo-text's specified stem darkening and 1/4-px origins), clipped
  to the text box `T`, with per-pixel [lo, hi] bounds over the scene
  oracle's own Home background (the real glass frost);
* the caret, exact: Electric Blue over its 2x24 rectangle, only while the
  field has the keyboard;
* the Home view's FNV-1a digest with ONLY that state's tight window masked
  (plus the bar's and the chip's label boxes, as in the Home fixture), so
  every other pixel of the text box is held to the background.

usage: field_oracle.py fixture > fixtures/desktop-ds1/field_text.rs
"""
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "fonts"))
sys.path.insert(0, HERE)

import area_oracle as ao  # noqa: E402
import label_oracle as lo  # noqa: E402
import scene_oracle as so  # noqa: E402

W, H = 1920, 1080
PLACEHOLDER = "Ask Arthur anything"
EB = 0x3C8EF4
# A long intent: wider than the box, so it scrolls left (its start clipped).
LONG = ("list every file in the home directory, then summarize what each one "
        "is for in one line please")
# (name, text, field has the keyboard)
STATES = [
    ("EMPTY_FOCUSED", "", True),
    ("TYPED_FOCUSED", "hello desktop", True),
    ("TYPED_UNFOCUSED", "hello desktop", False),
    ("SCROLLED_FOCUSED", LONG, True),
]


def text_box(L):
    return L["home_labels"][1]


def run(face, L, text, focused):
    """(glyph layers, colour, px, caret rect or None) for one field state."""
    tx, ty, tw, th = text_box(L)
    fx, fy, fw, fh = L["field"]
    base = fy + 35
    if not text:
        px, fg, words, x0 = 16.0, lo.SECONDARY, PLACEHOLDER, float(tx)
        caret_x = tx
    else:
        px, fg, words = 18.0, lo.PRIMARY, text
        w = lo.measure(face, px, text)
        room = float(tw - 4)
        x0 = tx + room - w if w > room else float(tx)
        caret_x = math.floor(x0 + w + 1.0)
    layers = lo.run_coverage(face, words, px, x0, base, text_box(L))
    caret = (caret_x, fy + 16, 2, 24) if focused else None
    return layers, fg, px, caret


def clip(r, box):
    x0, y0 = max(r[0], box[0]), max(r[1], box[1])
    x1 = min(r[0] + r[2], box[0] + box[2])
    y1 = min(r[1] + r[3], box[1] + box[3])
    return (x0, y0, max(0, x1 - x0), max(0, y1 - y0))


def window(layers, caret, box):
    keys = [k for cov in layers for k, a in cov.items() if a > 0]
    xs = [k[0] for k in keys]
    ys = [k[1] for k in keys]
    if caret:
        c = clip(caret, box)
        xs += [c[0], c[0] + c[2] - 1]
        ys += [c[1], c[1] + c[3] - 1]
    x0 = max(min(xs) - 1, box[0])
    y0 = max(min(ys) - 1, box[1])
    x1 = min(max(xs) + 2, box[0] + box[2])
    y1 = min(max(ys) + 2, box[1] + box[3])
    return (x0, y0, x1 - x0, y1 - y0)


def fixture():
    face = ao.Face(lo.FONT)
    L = so.layout(W, H)
    box = text_box(L)
    print("// SPDX-License-Identifier: MPL-2.0")
    print("// GENERATED by scripts/desktop/field_oracle.py fixture — do not edit.")
    print("// DS-1 Home intent field, exact (Codex DS-1a F2): per state, a tight window")
    print("// over the run and the caret with per-pixel [lo, hi] bounds (exact-area")
    print("// coverage +/-%d/255 over the scene oracle's Home background; the caret" % lo.SLACK)
    print("// exact), and the 1920x1080 Glass Home digest with ONLY that window and")
    print("// the bar's and chip's label boxes masked. Independent of neo-text and")
    print("// neo-atrium.")
    print("pub const LONG_INTENT: &str = %s;" % ('"' + LONG + '"'))
    print("/// (name, text, field has the keyboard), in WINDOWS order.")
    print("pub const STATES: [(&str, &str, bool); %d] = [" % len(STATES))
    for name, text, focused in STATES:
        t = "LONG_INTENT" if text == LONG else '"%s"' % text
        print("    (\"%s\", %s, %s)," % (name, t, "true" if focused else "false"))
    print("];")
    rows = []
    for name, text, focused in STATES:
        layers, fg, px, caret = run(face, L, text, focused)
        win = window(layers, caret, box)
        rgb, Lr = so.render(W, H, "glass", focused, "home")
        masks = [Lr["home_labels"][0], Lr["home_labels"][2], win]
        digest = so.digest(rgb, dict(Lr, labels=masks))

        def bg_at(x, y, rgb=rgb):
            p = rgb[y, x]
            return (int(p[0]) << 16) | (int(p[1]) << 8) | int(p[2])

        lo_t, hi_t = lo.bounds(layers, px, fg, win, bg_at)
        if caret:
            cx, cy, cw, ch = clip(caret, box)
            wx, wy, ww, _ = win
            for y in range(cy, cy + ch):
                for x in range(cx, cx + cw):
                    lo_t[(y - wy) * ww + (x - wx)] = EB
                    hi_t[(y - wy) * ww + (x - wx)] = EB
        rows.append((name, win, digest, lo_t, hi_t))
    print("/// The tight window (x, y, w, h) of each state, in STATES order.")
    print("pub const WINDOWS: [(usize, usize, usize, usize); %d] = [" % len(rows))
    for name, win, *_r in rows:
        print("    (%d, %d, %d, %d), // %s" % (win + (name,)))
    print("];")
    print("/// The Glass Home digest per state (bar and chip label boxes and that")
    print("/// state's window masked).")
    print("pub const DIGESTS: [u64; %d] = [" % len(rows))
    for name, _w, digest, *_r in rows:
        print("    0x%016x, // %s" % (digest, name))
    print("];")
    for name, win, _d, lo_t, hi_t in rows:
        for half, table in (("LO", lo_t), ("HI", hi_t)):
            print("#[rustfmt::skip]")
            print("pub static %s_%s: [u32; %d] = [" % (name, half, len(table)))
            ww = win[2]
            for i in range(0, len(table), ww):
                print("    " + ", ".join("0x%06x" % v for v in table[i:i + ww]) + ",")
            print("];")
    print("/// (LO, HI) per state, in STATES order.")
    print("pub static BOUNDS: [(&[u32], &[u32]); %d] = [" % len(rows))
    for name, *_r in rows:
        print("    (&%s_LO, &%s_HI)," % (name, name))
    print("];")


def main():
    if len(sys.argv) == 2 and sys.argv[1] == "fixture":
        fixture()
        return
    print(__doc__)
    sys.exit(2)


if __name__ == "__main__":
    main()
